# `dev doctor` and the devkit copies older than the pinned release: hooks or instructions an older copy wrote back,
# and other copies whose bin/dev still runs their own code, each with the command that fixes it.
# Run: python3 -m unittest tests.test_selfcheck_old_copies -v
import hashlib
import json
import os
import sys
import tempfile
import unittest
from pathlib import Path
from unittest import mock

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tests"))
import _hermetic  # noqa: E402

_hermetic.activate()
sys.path.insert(0, str(ROOT / "lib"))

from devkit import audit, core, selfcheck  # noqa: E402

OLD, NEW = "26.11.4-89079aa", "26.11.6-bbbbbbb"


class OldCopyRows(unittest.TestCase):
    """A temporary HOME: install.json pins NEW; OLD, an older copy, is kept for a rollback."""

    def setUp(self):
        tmp = tempfile.TemporaryDirectory()
        self.addCleanup(tmp.cleanup)
        self.home = Path(tmp.name).resolve()
        self.root = self.home / ".local" / "share" / "devkit" / "releases"
        for name in (OLD, NEW):
            (self.root / name / "bin").mkdir(parents=True)
            (self.root / name / "bin" / "dev").write_text("#!/usr/bin/env python3\n")
            (self.root / name / core.PIN_MANIFEST).write_text(json.dumps({"version": name.split("-")[0], "files": {}}))
        man = (self.root / NEW / core.PIN_MANIFEST).read_bytes()
        (self.root.parent / "install.json").write_text(json.dumps({
            "name": NEW, "version": "26.11.6", "path": str(self.root / NEW),
            "manifest_sha256": hashlib.sha256(man).hexdigest()}))
        self.claude, self.codex = self.home / ".claude", self.home / ".codex"
        for d in (self.claude, self.codex):
            d.mkdir()
        for p in (mock.patch.object(core, "HOME", self.home), mock.patch.object(core, "DEVKIT_HOME", ROOT),
                  mock.patch.object(audit, "AUDIT", self.home / "audit")):
            p.start()
            self.addCleanup(p.stop)
        self.write(NEW, "26.11.6")

    def write(self, hooks_copy, instructions_version):
        dev = f"'{self.root / hooks_copy}/bin/dev'"
        (self.claude / "settings.json").write_text(json.dumps({
            "hooks": {"PreToolUse": [{"matcher": "Bash", "hooks": [{"type": "command",
                                                                    "command": f"{dev} hook guard --agent claude"}]}]},
            "statusLine": {"type": "command", "command": f"{dev} hook statusline --agent claude"}}))
        (self.codex / "hooks.json").write_text(json.dumps({"hooks": {"SessionStart": [{"hooks": [
            {"type": "command", "command": f"{self.root / NEW}/bin/dev hook session-start --agent codex"}]}]}}))
        for f in (self.claude / "CLAUDE.md", self.codex / "AGENTS.md"):
            f.write_text(f"<!-- generated by devkit {instructions_version} from ~/devkit/agents/AGENTS.md; edit those "
                         f"and run `dev install` -->\n# Global instructions\n")

    def rows(self) -> dict:
        found = selfcheck.old_copy_checks(claude_home=self.claude, codex_home=self.codex,
                                          managed=self.home / "managed.json")
        self.assertTrue(all(len(r) == 5 for r in found), found)
        return {name: (ok, detail, fix) for _, name, ok, detail, fix in found}

    def retire_old(self):
        dev = self.root / OLD / "bin" / "dev"
        dev.unlink()
        dev.symlink_to(self.root / NEW / "bin" / "dev")

    def test_all_current_and_retired_reads_ok(self):
        self.retire_old()
        rows = self.rows()
        self.assertEqual({k: v[0] for k, v in rows.items()},
                         {"agents run the pinned release": True, "older copies retired": True})

    def test_hooks_and_instructions_an_older_copy_wrote_back_are_named_with_the_fix(self):
        self.retire_old()
        self.write(OLD, "26.11.4")
        ok, detail, fix = self.rows()["agents run the pinned release"]
        self.assertFalse(ok)
        for what in ("Claude PreToolUse", "Claude status line", "CLAUDE.md", "AGENTS.md", "26.11.4", "26.11.6"):
            self.assertIn(what, detail)
        self.assertNotIn("Codex SessionStart", detail)  # it runs the pinned release
        self.assertIn("dev config repair", fix)
        self.assertIn("restart", fix)

    def test_a_copy_whose_dev_still_runs_its_own_code_is_named(self):
        ok, detail, fix = self.rows()["older copies retired"]
        self.assertFalse(ok)
        self.assertIn(OLD, detail)
        self.assertNotIn(NEW, detail)
        self.assertIn("dev config repair", fix)

    def test_a_newer_instructions_header_is_not_older(self):
        self.retire_old()
        self.write(NEW, "26.12.0")
        self.assertTrue(self.rows()["agents run the pinned release"][0])

    def test_nothing_to_report_without_a_pin_that_holds_up(self):
        (self.root.parent / "install.json").write_text(json.dumps({"name": NEW, "path": str(self.root / NEW)}))
        self.write(OLD, "26.11.4")
        self.assertEqual(self.rows(), {})


if __name__ == "__main__":
    unittest.main()
