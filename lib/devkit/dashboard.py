def safe_json(obj) -> str:
    """JSON that is safe inside <script type="application/json">: no raw <, > or & anywhere."""
    s = json.dumps(obj, ensure_ascii=False, separators=(",", ":"), default=str)
    return (s.replace("&", "\\u0026").replace("<", "\\u003c").replace(">", "\\u003e")
             .replace("\u2028", "\\u2028").replace("\u2029", "\\u2029"))


def _session_ts(line: str) -> int:
    m = re.match(r"^(\d{4}-\d{2}-\d{2}) (\d{2}):(\d{2})", line or "")
    if not m:
        return 0
    try:
        return int(time.mktime(time.strptime(f"{m.group(1)} {m.group(2)}:{m.group(3)}", "%Y-%m-%d %H:%M")))
    except (ValueError, OverflowError):
        return 0


def _iso_ts(s) -> int:
    try:
        return int(calendar.timegm(time.strptime(str(s)[:19], "%Y-%m-%dT%H:%M:%S")))
    except (ValueError, TypeError):
        return 0


def _midnight(now: float, days_back: int = 0) -> int:
    t = time.localtime(now - days_back * 86400)
    return int(time.mktime((t.tm_year, t.tm_mon, t.tm_mday, 0, 0, 0, 0, 0, -1)))


def _mine(pr: dict, me: str) -> bool:
    author = (pr.get("author") or "").lower()
    return not me or not author or author == me.lower()


def _open_tasks(ns: dict) -> list:
    t = (ns or {}).get("tasks") or {}
    return list(t.get("now") or []) + list(t.get("next") or []) + list(t.get("later") or [])


def task_index(ns: dict, text: str):
    """1-based index of an open task as `dev task` numbers them (Now, Next, Later order)."""
    open_ = _open_tasks(ns)
    return open_.index(text) + 1 if text in open_ else None


def _idle(ts, now) -> float:
    return now - (ts or now)


def explorer_files(handoff: Path, cap: int = EXPLORER_CAP):
    """Markdown files of the handoff repo, root files first then newest first, until `cap` bytes."""
    root = Path(handoff)
    cands = set()
    for name in ROOT_FILES:
        if (root / name).is_file():
            cands.add(root / name)
    for sub in ("initiatives", "projects", "plans", "log"):
        d = root / sub
        if d.is_dir():
            cands.update(p for p in d.rglob("*.md") if p.is_file())

    def mtime(p):
        try:
            return p.stat().st_mtime
        except OSError:
            return 0

    files, total, omitted = [], 0, 0
    for f in sorted(cands, key=lambda p: (p.name not in ROOT_FILES or p.parent != root, -mtime(p))):
        try:
            text = f.read_text(errors="replace")
        except OSError:
            continue
        size = len(text.encode("utf-8", "replace"))
        if total + size > cap:
            omitted += 1
            continue
        total += size
        files.append({"path": str(f.relative_to(root)), "mtime": int(mtime(f)), "size": size, "text": text})
    return files, {"capped": omitted > 0, "omitted": omitted, "bytes": total, "cap": cap}


def pr_cache() -> dict:
    """{owner/repo: [pr]} from devkit's PR cache (~/.local/state/devkit/prs/*.json), all states."""
    out = {}
    d = core.STATE / "prs"
    try:
        for f in d.glob("*.json"):
            try:
                out[f.stem.replace("__", "/", 1)] = json.loads(f.read_text()) or []
            except (OSError, ValueError):
                continue
    except OSError:
        pass
    return out


def merged_prs(cache: dict, since_ts: float) -> list:
    out = []
    for repo, prs in cache.items():
        for pr in prs or []:
            ts = _iso_ts(pr.get("updatedAt") or pr.get("updated"))
            if pr.get("state") == "MERGED" and ts >= since_ts:
                out.append({"repo": repo, "number": pr.get("number"), "title": pr.get("title") or "",
                            "url": pr.get("url") or "", "ts": ts, "author": pr.get("author") or ""})
    return sorted(out, key=lambda x: -x["ts"])


