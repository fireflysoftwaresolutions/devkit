def project_health(p: dict, now: float = None) -> dict:
    """{level: ok|warn|risk, reasons: [...]} from PRs, note status, tasks and git state."""
    now = now or time.time()
    risk, warn = [], []
    for pr in p.get("prs_open") or []:
        n = pr.get("number")
        if pr.get("checks") == "failing":
            risk.append(f"PR #{n} is failing CI")
        if pr.get("review") == "CHANGES_REQUESTED":
            risk.append(f"PR #{n} has changes requested")
        if pr.get("mergeable") == "CONFLICTING":
            warn.append(f"PR #{n} has merge conflicts")
    ns = p.get("note_summary") or {}
    if ns.get("status") == "blocked":
        risk.append("marked blocked in the handoff note")
    for t in ((ns.get("tasks") or {}).get("overdue") or []):
        risk.append("overdue task: " + re.sub(r"\s*\bdue:\S+", "", t)[:60])
    m = p.get("main") or {}
    dirty = (m.get("modified") or 0) + (m.get("untracked") or 0)
    if dirty and not m.get("active") and _idle(m.get("last_activity"), now) > IDLE_WORK_S:
        warn.append(f"{dirty} uncommitted change(s), idle {int(_idle(m.get('last_activity'), now) // 86400)}d")
    if m.get("unpushed") and not m.get("active") and _idle(m.get("last_activity"), now) > 86400:
        warn.append(f"{m['unpushed']} commit(s) not pushed")
    for w in p.get("worktrees") or []:
        wd = (w.get("modified") or 0) + (w.get("untracked") or 0)
        if (wd or w.get("unpushed")) and not w.get("active") and _idle(w.get("last_activity"), now) > IDLE_WORK_S:
            warn.append(f"worktree {w.get('branch')} has unsaved work, idle")
    if p.get("canonical_ok") is False and p.get("local", True) is not False:
        warn.append("not at its canonical path")
    if ns.get("due") and ns["due"] < time.strftime("%Y-%m-%d", time.localtime(now)) and ns.get("status") not in ("done", "archived"):
        risk.append(f"past its due date ({ns['due']})")
    level = "risk" if risk else "warn" if warn else "ok"
    return {"level": level, "reasons": risk + warn}


def build_actions(reg: dict, now: float = None) -> list:
    """The prioritised 'what needs me now' list. Each item carries the one command that moves it forward."""
    now = now or time.time()
    me = reg.get("github_user") or ""
    acts = []

    def add(rank, sev, kind, project, title, detail, cmd, url=None, ts=0):
        acts.append({"rank": rank, "sev": sev, "kind": kind, "project": project, "title": title, "detail": detail,
                     "cmd": cmd, "url": url, "ts": int(ts or 0)})

    reclaim = []
    for p in reg.get("projects") or []:
        pid, repo = p.get("id"), p.get("github") or p.get("id")
        wts = {w.get("branch"): w for w in p.get("worktrees") or []}
        default = p.get("default_branch") or "main"
        for pr in p.get("prs_open") or []:
            n, ts, mine = pr.get("number"), _iso_ts(pr.get("updated")), _mine(pr, me)
            title = pr.get("title") or ""
            if mine and pr.get("checks") == "failing":
                add(10, "risk", "ci-failing", pid, f"PR #{n} is failing CI", title,
                    f"gh pr checks {n} -R {repo} --watch", pr.get("url"), ts)
            if mine and pr.get("review") == "CHANGES_REQUESTED":
                add(20, "risk", "changes-requested", pid, f"PR #{n}: changes requested", title,
                    f"gh pr view {n} -R {repo} --comments", pr.get("url"), ts)
            if mine and pr.get("mergeable") == "CONFLICTING":
                w = wts.get(pr.get("branch"))
                cmd = (f"cd {w['path']} && git fetch origin && git rebase origin/{default}" if w and w.get("path")
                       else f"dcd {pid} && gh pr checkout {n} && git rebase origin/{default}")
                add(22, "warn", "conflicts", pid, f"PR #{n} has merge conflicts", title, cmd, pr.get("url"), ts)
            if pr.get("review") == "REVIEW_REQUIRED" and pr.get("checks") != "failing" and not pr.get("draft"):
                if mine:
                    add(30, "warn", "review-waiting", pid, f"PR #{n} is waiting for review", title,
                        f"gh pr view {n} -R {repo} --web", pr.get("url"), ts)
                else:
                    add(32, "warn", "review-requested", pid, f"Review PR #{n} by @{pr.get('author')}", title,
                        f"gh pr diff {n} -R {repo}", pr.get("url"), ts)
        ns = p.get("note_summary") or {}
        if ns.get("status") == "blocked":
            state = [re.sub(r"^\s*([-*+]|\d+\.)\s*(\[[ xX~]\]\s*)?", "", ln).strip()
                     for ln in (ns.get("state") or "").splitlines() if ln.strip()]
            add(40, "risk", "blocked", pid, f"{p.get('name') or pid} is blocked", state[0][:160] if state else "",
                f"dev handoff {pid}", None, p.get("last_activity"))
        for t in (ns.get("tasks") or {}).get("overdue") or []:
            due = re.search(r"\bdue:(\d{4}-\d{2}-\d{2})", t)
            k = task_index(ns, t)
            add(50, "risk", "overdue", pid, "Overdue task" + (f" (due {due.group(1)})" if due else ""),
                re.sub(r"\s*\bdue:\S+", "", t), f"dev task done {k} -p {pid}" if k else f"dev handoff {pid}")
        m = p.get("main") or {}
        checkouts = [(p.get("path"), m.get("branch"), m)] + [(w.get("path"), w.get("branch"), w)
                                                           for w in p.get("worktrees") or [] if not w.get("missing")]
        for path, branch, co in checkouts:
            if co.get("active"):
                continue
            dirty = (co.get("modified") or 0) + (co.get("untracked") or 0)
            idle = _idle(co.get("last_activity"), now)
            if dirty and idle > IDLE_WORK_S:
                add(60, "warn", "idle-work", pid, f"{dirty} uncommitted change(s) idle {int(idle // 86400)}d",
                    f"{p.get('name') or pid} · {branch}", f"cd {path} && git status -sb", None, co.get("last_activity"))
            elif co.get("unpushed") and idle > 86400:
                add(62, "warn", "idle-work", pid, f"{co['unpushed']} commit(s) not pushed",
                    f"{p.get('name') or pid} · {branch}", f"cd {path} && git status -sb", None, co.get("last_activity"))
        for w in p.get("worktrees") or []:
            pr = w.get("pr") or {}
            clean = not (w.get("modified") or w.get("untracked") or w.get("unpushed"))
            if pr.get("state") in ("MERGED", "CLOSED") and not w.get("active") and clean and not w.get("missing"):
                reclaim.append((pid, w.get("branch"), pr.get("number"), pr.get("state"), w.get("size_kb") or 0))
        if p.get("canonical_ok") is False and p.get("path") and p.get("local", True) is not False:
            add(80, "info", "layout", pid, f"{p.get('name') or pid} is outside the workspace layout",
                f"canonical path: {core.tilde(p.get('canonical') or '')}", f"dev adopt {core.tilde(p['path'])}")
        if ns:
            last = max([_session_ts(s) for s in ns.get("sessions") or []] or [0])
            recent = sum(v for k, v in (p.get("activity") or {}).items()
                         if k >= time.strftime("%Y-%m-%d", time.localtime(now - 7 * 86400)))
            if recent and (p.get("last_activity") or 0) - last > 3 * 86400:
                add(85, "info", "stale-note", pid, "Handoff note is behind the code",
                    f"{recent} commit(s) this week, " + ("no session logged yet" if not last else
                                                         "last session " + time.strftime("%b %d", time.localtime(last))),
                    f"dev handoff {pid}")
    if len(reclaim) == 1:
        pid, br, n, st, kb = reclaim[0]
        add(70, "info", "reclaim", pid, f"Worktree {br} is done (PR #{n} {st.lower()})", f"{kb // 1024} MB to reclaim",
            f"dev wt rm {br}")
    elif reclaim:
        add(70, "info", "reclaim", None, f"{len(reclaim)} finished worktrees to reclaim",
            ", ".join(f"{br} (#{n})" for _, br, n, _, _ in reclaim[:5]) +
            f" · {sum(r[4] for r in reclaim) // 1024} MB", "dev gc --apply")
    today = time.strftime("%Y-%m-%d", time.localtime(now))
    for ini in reg.get("initiatives") or []:
        if not isinstance(ini, dict):
            continue
        slug, title = ini.get("id"), ini.get("title") or ini.get("id")
        if ini.get("status") == "blocked":
            state = [re.sub(r"^\s*([-*+]|\d+\.)\s*(\[[ xX~]\]\s*)?", "", ln).strip()
                     for ln in (ini.get("state") or ini.get("risks") or "").splitlines() if ln.strip()]
            add(41, "risk", "blocked", None, f"Initiative {title} is blocked", state[0][:160] if state else "",
                f"dev initiative show {slug}", None, ini.get("last_activity"))
        if ini.get("due") and ini["due"] < today and ini.get("status") not in ("done", "archived"):
            add(45, "risk", "overdue", None, f"Initiative {title} is past its due date ({ini['due']})",
                (f"{ini.get('progress')}% done" if ini.get("progress") is not None else "") +
                (f" · milestone {ini['milestone']}" if ini.get("milestone") else ""), f"dev initiative show {slug}")
        for t in ((ini.get("tasks") or {}).get("overdue") or []):
            k = task_index({"tasks": ini.get("tasks")}, t)
            due = re.search(r"\bdue:(\d{4}-\d{2}-\d{2})", t)
            add(50, "risk", "overdue", None, f"Overdue in {title}" + (f" (due {due.group(1)})" if due else ""),
                re.sub(r"\s*\bdue:\S+", "", t), f"dev task done {k} -i {slug}" if k else f"dev initiative show {slug}")
    drift = reg.get("drift")
    if drift:
        add(90, "warn", "drift", None, f"Agent configuration drifted ({len(drift)} setting(s))",
            "Claude Code or Codex no longer match the devkit configuration", "dev config diff")
    for key, prov in ((reg.get("providers") or {}).items()):
        if isinstance(prov, dict) and prov.get("installed") and prov.get("logged_in") is False:
            add(95, "warn", "sign-in", None, f"{prov.get('name') or key} is not signed in", "",
                "claude" if key == "claude" else "codex login")
    acts.sort(key=lambda a: (a["rank"], -a["ts"]))
    return acts


def since_yesterday(reg: dict, cache: dict, now: float = None) -> dict:
    """What happened since the start of yesterday: sessions, commits, merged PRs, completed tasks."""
    now = now or time.time()
    y0 = _midnight(now, 1)
    yday = time.strftime("%Y-%m-%d", time.localtime(y0))
    sessions = []
    for s in reg.get("sessions") or []:
        ts = s.get("last_seen") or s.get("started") or 0
        if ts >= y0:
            sessions.append({"ts": ts, "project": s.get("project"), "agent": s.get("agent"),
                             "branch": s.get("branch"), "text": s.get("status") or "", "live": bool(s.get("active"))})
    seen = {(x["project"], x["agent"]) for x in sessions}
    for p in reg.get("projects") or []:
        for line in ((p.get("note_summary") or {}).get("sessions") or []):
            ts = _session_ts(line)
            if ts >= y0:
                body = re.sub(r"^\d{4}-\d{2}-\d{2} \d{2}:\d{2}\s*·\s*", "", line)
                agent = body.split(" · ", 1)[0]
                if (p.get("id"), agent) in seen and ts < max([x["ts"] for x in sessions if x["project"] == p.get("id")] or [0]):
                    continue
                sessions.append({"ts": ts, "project": p.get("id"), "agent": agent, "branch": "",
                                 "text": body.split(" · ", 1)[1] if " · " in body else body, "live": False})
    commits = []
    for p in reg.get("projects") or []:
        n = sum(v for k, v in (p.get("activity") or {}).items() if k >= yday)
        if n:
            commits.append([p.get("id"), n])
    done = []
    for p in reg.get("projects") or []:
        for t in ((p.get("note_summary") or {}).get("tasks") or {}).get("done_recent") or []:
            m = re.search(r"✓\s*(\d{4}-\d{2}-\d{2})", t)
            if m and m.group(1) >= yday:
                done.append({"project": p.get("id"), "text": re.sub(r"\s*✓\s*\d{4}-\d{2}-\d{2}", "", t)})
    return {"from": y0, "sessions": sorted(sessions, key=lambda x: -x["ts"])[:40],
            "commits": sorted(commits, key=lambda x: -x[1]), "merged": merged_prs(cache, y0)[:20], "done": done[:30]}


