UNKNOWN = Path("/__devkit_unknown__")


def resolve(path, cwd) -> Path:
    """Absolute real path, or UNKNOWN when it depends on shell state the hook cannot see ($VAR, $(…), `…`)."""
    p = os.path.expanduser(os.path.expandvars(str(path)))
    if "$" in p or "`" in p:
        return UNKNOWN
    if not os.path.isabs(p):
        if cwd is None or str(cwd) == str(UNKNOWN):
            return UNKNOWN
        p = os.path.join(cwd, p)
    return Path(real(p))


def allowed_tops() -> set:
    tops = set(RESERVED_TOP) | core.owners()
    try:
        tops |= {e.name.lower() for e in os.scandir(DEV) if e.is_dir()}
    except OSError:
        pass
    return tops


def layout_violation(p: Path, creating_dir=False):
    """Reason string when `p` breaks the ~/Development layout, else None."""
    if p == UNKNOWN or not is_under(p, DEV) or real(p) == real(DEV):
        return None
    rel = Path(real(p)).relative_to(real(DEV)).parts
    if len(rel) == 1 and not creating_dir and not rel[0].startswith("."):
        if not (Path(real(DEV)) / rel[0]).is_dir():
            return f"Files do not go directly in {tilde(DEV)} ({rel[0]}). " + LAYOUT_HINT
    top = rel[0].lower()
    if top not in allowed_tops() and not top.startswith(".") and "." not in top:
        return (f"`{tilde(DEV)}/{rel[0]}` is not a GitHub owner folder you belong to, nor _local. "
                f"Sibling copies like `<repo>-pr12` or `<repo>-copy` are not allowed. " + LAYOUT_HINT)
    return None


GENERATED = {"PROJECTS.md", "TASKS.md", "ACTIVITY.md", "registry.json"}


def current_project(cwd):
    """Project id of the session's working directory, or None for portfolio-level sessions."""
    if not cwd or str(cwd) == str(UNKNOWN):
        return None
    top = core.gitout(cwd, "rev-parse", "--show-toplevel")
    if not top or is_temp(top) or real(top) == real(core.HANDOFF):
        return None
    from .registry import main_of
    main = main_of(Path(top)) or Path(top)
    return core.project_identity(main, core.gitout(main, "config", "--get", "remote.origin.url"))[0]


