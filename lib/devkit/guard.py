class _Shell:
    """Walks one shell command for writes to protected paths; `unresolved` collects targets it cannot resolve, and
    `exported` the variables the shell has set so far (export, bare assignments: they reach later commands)."""

    def __init__(self, cmd: str, cwd, outer_mentions=False, depth=0, exported=()):
        self.cmd, self.cwd, self.depth = cmd, cwd, depth
        self.mentions = outer_mentions or bool(_mark().search(cmd))
        self.keys = sorted(set(_KEY_TEXT.findall(_unescape(cmd))))
        self.bodies = heredoc_bodies(cmd)
        self.unresolved = []
        self.exported = set(exported)

    def target(self, t, cwd, verb="write", holds=False, track=True):
        lp = _lexical(t, cwd)
        if is_dev_command(lp) or (holds and holds_dev_command(lp)):
            return deny(dev_command_reason(lp, verb))
        p = resolve(t, cwd)
        if p == UNKNOWN:
            if track and t:
                self.unresolved.append(t)
            return None
        if is_protected(p) or (holds and holds_protected(p)):
            return deny(protected_reason(p, verb))
        if holds and holds_dev_command(p):
            return deny(dev_command_reason(p, verb))
        if env_file_kind(p, lp) and self.keys:
            return deny(_settings_reason(p, self.keys))
        return None

    def targets(self, ts, cwd, verb="write", holds=False, track=True):
        for t in ts:
            v = self.target(t, cwd, verb, holds, track)
            if v:
                return v
        return None

    def run(self):
        segs = split_commands(self.cmd)
        if segs is None:
            if self.mentions and re.search(r">|\b(tee|cp|mv|rm|ln|sed|python|perl|ruby|node|dd|install)\b", self.cmd):
                return deny("This command names devkit's state, configuration or install, writes files, and the guard "
                            "cannot parse it to see where (spec C11: agents may not write them). Split it into "
                            f"simple commands. {_TAIL}")
            return None
        cwd = self.cwd
        for argv0, redirs in segs:
            argv0, clobber, k = list(argv0), [], 0
            while k < len(argv0):  # `>|` reaches argv as a token; the next token is its target
                if argv0[k] in (">|", ">>|"):
                    clobber.append(argv0[k + 1] if k + 1 < len(argv0) else "")
                    del argv0[k:k + 2]
                    continue
                k += 1
            v = self.targets(list(redirs) + clobber, cwd)
            if v:
                return v
            prefix = argv0[:len(argv0) - len(_strip_prefix(argv0))]
            assigns = [a.split("=", 1)[1] for a in prefix if re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", a)]
            names, argv = _env_split(argv0)
            if not argv:  # `HOME=/x;` changes the shell's own variable, which an exported HOME passes on
                self.exported |= names
                continue
            name = os.path.basename(argv[0])
            if argv[0][:1] in ("$", "`") and any(os.path.basename(h) == "env" for h in argv0[:len(argv0) - len(argv)]):
                self.exported.add("?")  # `env $(…) dev`: the tokenizer splits it; what it sets is not visible
            if name in ("cd", "pushd"):
                cwd = str(core.HOME) if len(argv) == 1 else cwd if argv[1] == "-" else str(resolve(argv[1], cwd))
                continue
            self.exported |= _exports(name, argv[1:])
            v = self.segment(name, argv, assigns, cwd, names)
            if v:
                return v
        if self.unresolved and self.mentions:
            return deny(f"This command writes to `{self.unresolved[0]}`, which depends on a variable or a subshell the "
                        f"guard cannot see, and it names devkit's state, configuration or install (spec C11: agents "
                        f"may not write them). Write the path out in full if it is not devkit's; otherwise use the "
                        f"`dev` command that owns the record. {_TAIL}")
        return None

    def nested(self, text, cwd, same_shell=False, names=()):
        if not text or self.depth >= 4:
            return None
        inner = _Shell(text, cwd, self.mentions, self.depth + 1, self.exported | set(names))
        v = inner.run()
        self.unresolved += inner.unresolved
        if same_shell:  # source and eval run in this shell: what they export stays set
            self.exported |= inner.exported
        return v

    def devkit_call(self, name, argv, cwd):
        """What reads devkit's state and configuration in this command, or None: `dev` (any path, python bin/dev,
        python -m devkit…), a program that imports devkit, or an agent session (its hooks run devkit)."""
        if _dev_args(argv) is not None:
            return "a devkit command"
        if name in _AGENT_CLIS:
            return f"a nested {name} session, whose hooks run devkit"
        if _INTERP.match(name) and len(argv) > 1:
            if argv[1] == "-m" and len(argv) > 2 and argv[2].split(".")[0] == "devkit":
                return "a devkit command"
            code = _program(argv, cwd, self.bodies)[0]
            if code and _DEVKIT_PY.search(code):
                return "a program that imports devkit"
        return None

    def forged_env(self, name, argv, cwd, names):
        """A segment that runs devkit with HOME, DEV_ROOT or a DEVKIT_* variable other than the hatches set by this
        command, or an interpreter program that sets one in its environment and runs devkit (K1 follow-ups 2, 3)."""
        if name == "launchctl" and argv[1:2] == ["setenv"] and len(argv) > 2 and \
                (_forged({argv[2]}) or argv[2] in ENV_HATCHES):
            return deny(f"`launchctl setenv {argv[2]}` sets it for every app and job launchd starts from now on, the "
                        f"agents' desktop apps and devkit's jobs included, and devkit reads it there (spec C11, K1). "
                        f"Agents may not. {_TAIL}")
        what = self.devkit_call(name, argv, cwd)
        if what:
            bad = _forged(set(names) | self.exported)
            if bad:
                return deny(forged_env_reason(bad, what))
        if _INTERP.match(name) and not _repo_script(argv, cwd):
            code = _program(argv, cwd, self.bodies)[0]
            if code and _DEV_RUN_CODE.search(code):
                bad = _forged({n for m in _ENV_SET_CODE.finditer(code) for n in _ENV_NAME.findall(m.group(0))})
                if bad:
                    return deny(forged_env_reason(bad, f"the devkit command this {name} program runs"))
        return None

    def segment(self, name, argv, assigns, cwd, names=()):
        args = argv[1:]
        v = self.forged_env(name, argv, cwd, names)
        if v:
            return v
        dev = _dev_args(argv)
        if dev is not None:
            return self.dev(dev, cwd)
        installer = argv[0] if name == "install.sh" else next(
            (a for a in args if not a.startswith(("-", "+"))), "") if name in _SHELLS else ""
        if installer and _devkit_installer(resolve(installer, cwd)):
            return deny(INSTALL_REASON)
        if name in _SHELLS:
            for text in _shell_inputs(args, cwd, self.bodies):
                v = self.nested(text, cwd, names=names)
                if v:
                    return v
            return None
        if name in ("source", ".") and args:
            return self.nested(_read_small(resolve(args[0], cwd)), cwd, same_shell=True)
        if name == "eval":
            return self.nested(" ".join(args), cwd, same_shell=True)
        if name == "xargs":
            return self.xargs(args, cwd)
        if name == "find":
            return self.find(args, cwd)
        if _INTERP.match(name):
            return self.interpreter(argv, assigns, cwd)
        if name in _COPIERS or name in _MOVERS:
            return self.copy(name, args, cwd)
        if name in _CREATORS:
            return self.targets(_candidates(args), cwd)
        if name in _CHANGERS:
            return self.targets(_candidates(args), cwd, "change or delete", holds=True)
        if name == "dd":
            return self.targets([a[3:] for a in args if a.startswith("of=")], cwd)
        if name in ("sed", "yq"):
            inplace = any(a == "--in-place" or a.startswith(("--in-place=", "--inplace")) or
                          (a.startswith("-") and not a.startswith("--") and "i" in a[1:]) for a in args)
            return self.targets(_candidates(args), cwd) if inplace else None
        if name == "sort":
            out = _opt_value(args, ("-o", "--output"))
            return self.target(out, cwd) if out else None
        if name == "uniq":
            pos = [a for a in args if not a.startswith("-")]
            return self.target(pos[1], cwd) if len(pos) > 1 else None
        if name in _READERS:
            return None
        # anything else (editors, sqlite3, git, curl, tar, …) may write the paths it is given
        inside = is_protected(Path(cwd)) if cwd and str(cwd) != str(UNKNOWN) else False
        return self.targets([c for c in _candidates(args) if inside or _pathlike(c)], cwd)

    def dev(self, args, cwd):
        if args[:1] in (["install"], ["update"]) and not {"-h", "--help"} & set(args[1:]):
            return deny(INSTALL_REASON)
        if args[:2] == ["config", "set"]:
            keys = [k for a in args[2:] for k in {a.casefold(), a.casefold().split("=", 1)[-1]}]
            if any(k.startswith("safeguards") for k in keys):
                return deny(SAFEGUARDS_REASON)
            if any(re.match(r"audit(?:\.|=|$)", k) for k in keys):
                return deny(AUDIT_REASON)
        if args[:2] == ["config", "edit"]:
            return deny(protected_reason(Path(real(core.CONFIG_FILE)), "edit"))
        if args[:1] in (["rm"], ["mv"], ["cp"]):
            return self.segment(args[0], args, [], cwd)
        if args[:1] and (args[0] in _DEV_READ or args[0] in _DEV_TEXT):
            return None
        # devkit's own commands write the state in their process; only a path argument that lands in it is refused
        return self.targets([c for c in _candidates(args[1:]) if _pathlike(c)], cwd, track=False)

    def copy(self, name, args, cwd):
        pos = [a for a in args if not a.startswith("-")]
        tdir = _opt_value(args, ("-t", "--target-directory"))
        if name == "install" and "-d" in args:
            return self.targets(pos, cwd)
        if tdir:
            dests, srcs = [tdir], [p for p in pos if p != tdir]
        elif len(pos) >= 2:
            dests, srcs = pos[-1:], pos[:-1]
        else:
            return None
        links = name in ("cp", "gcp") and any(a in ("--link", "--symbolic-link") or (
            a.startswith("-") and not a.startswith("--") and ("l" in a or "s" in a)) for a in args)
        if name in _MOVERS or links:  # a move deletes the source; a link is a way in
            v = self.targets(srcs, cwd, "move" if name in _MOVERS else "link", holds=True)
            if v:
                return v
        for d in dests:
            v = self.target(d, cwd)
            if v:
                return v
            dp = resolve(d, cwd)
            if dp == UNKNOWN:
                continue
            if dp.is_dir():
                v = self.targets([str(dp / os.path.basename(s.rstrip("/"))) for s in srcs], cwd)
                if v:
                    return v
            kind = env_file_kind(dp, _lexical(d, cwd))
            if kind:
                toml, shell = kind == "toml", kind == "shell"
                now = devkit_env(_read_small(dp, 1 << 20), toml, shell)
                for s in srcs:
                    new = devkit_env(_read_small(resolve(s, cwd), 1 << 20), toml, shell)
                    if new != now:
                        return deny(_settings_reason(dp, sorted(k for k in set(new) | set(now)
                                                                if new.get(k) != now.get(k))))
        return None

    def xargs(self, args, cwd):
        i, takes = 0, {"-I", "-n", "-P", "-L", "-d", "-E", "-s", "-a", "-J", "-R", "-S"}
        while i < len(args) and args[i].startswith("-"):
            i += 2 if args[i] in takes else 1
        names, inner = _env_split(args[i:])
        if not inner:
            return None
        name = os.path.basename(inner[0])
        if name not in _READERS:  # it adds paths read from its input, which the guard cannot see
            self.unresolved.append(f"xargs {name}")
        return self.segment(name, inner, [], cwd, names)

    def find(self, args, cwd):
        acts = {"-delete", "-exec", "-execdir", "-ok", "-okdir", "-fprint", "-fprint0", "-fprintf", "-fls"}
        if not any(a in acts for a in args):
            return None
        roots = []
        for a in args:
            if a.startswith("-") or a in ("(", ")", "!", ","):
                break
            roots.append(a)
        writes = "-delete" in args
        for k, a in enumerate(args):
            if a in ("-fprint", "-fprint0", "-fprintf", "-fls") and k + 1 < len(args):
                v = self.target(args[k + 1], cwd)
                if v:
                    return v
            if a in ("-exec", "-execdir", "-ok", "-okdir") and k + 1 < len(args):
                inner = args[k + 1:]
                inner = inner[:next((j for j, x in enumerate(inner) if x in (";", "+")), len(inner))]
                inames, inner = _env_split(inner)
                iname = os.path.basename(inner[0]) if inner else ""
                v = self.forged_env(iname, inner, cwd, inames) if inner else None
                if v:
                    return v
                inplace = iname in ("sed", "yq") and any(x.startswith("-i") or x.startswith("--in") for x in inner)
                writes = writes or iname not in _READERS or inplace
        return self.targets(roots or ["."], cwd, "change or delete", holds=True) if writes else None

    def interpreter(self, argv, assigns, cwd):
        code, rest, module, inplace = _program(argv, cwd, self.bodies)
        name = os.path.basename(argv[0])
        inside = bool(cwd) and str(cwd) != str(UNKNOWN) and is_protected(Path(cwd))
        if _repo_script(argv, cwd) and not inside:
            module = name  # a repository's own script (a test) is its code, like `-m`: only its path arguments count
            pos = [a for a in rest if not a.startswith("-")]
            return self.targets(pos[1:2] if module == "json.tool" else [c for c in _candidates(rest) if _pathlike(c)],
                                cwd, track=False)
        if inplace:
            v = self.targets([a for a in rest if not a.startswith("-")], cwd)
            if v:
                return v
        if not code or not _CODE_WRITES.search(code):
            return None
        if not cwd or str(cwd) == str(UNKNOWN):  # its relative paths land in a folder the guard cannot see
            self.unresolved.append(f"a path relative to the folder {name} runs in")
        named = [c for c in _candidates(rest) + assigns if _pathlike(c)]
        # started inside devkit's state or configuration, its relative paths land there (Seraph, K1 review)
        hit = inside or _mark().search(code) or any(is_protected(resolve(c, cwd)) for c in named) or \
            (self.mentions and _CODE_INPUTS.search(code)) or ("DEVKIT_" in _unescape(code) and _SETTINGS_NAME.search(code)) \
            or _DEV_LINK_TEXT.search(code) or _dev_command_text().search(code)
        if not hit:
            return None
        return deny(f"This {name} program writes files and names devkit's state, configuration or install, or a "
                    f"DEVKIT_* setting (spec C11: agents may not write them; devkit's own commands do), and the guard "
                    f"cannot see which file it writes. To change a repository file whose text names them (a test, a "
                    f"doc), use the Edit or Write tool, which checks the path it writes, not the text. For a devkit "
                    f"record, use the `dev` command that owns it (`dev progress`, `dev task`, …). To read a record, "
                    f"open it without 'w' or 'a' and print it. {_TAIL}")


def _unwrap(argv):
    """The command a segment really runs: without env/sudo/nohup prefixes, shell keywords (`then`, `do`, `{`, `!`),
    `timeout N`, `uv run`, `npx`."""
    while True:
        argv = _strip_prefix(argv)
        if not argv:
            return argv
        n = os.path.basename(argv[0])
        if argv[0] in _RESERVED:
            argv = argv[1:]
        elif n in ("timeout", "gtimeout"):
            rest = argv[1:]
            while rest and rest[0].startswith("-"):
                rest = rest[1:]
            argv = rest[1:]
        elif (n in ("uv", "poetry", "pipenv", "pdm", "hatch", "rye") and argv[1:2] == ["run"]) or \
                (n == "pnpm" and argv[1:2] in (["exec"], ["dlx"])):
            argv = argv[2:]
            while argv and argv[0].startswith("-"):
                argv = argv[1:]
        elif n in ("npx", "bunx", "uvx", "pnpx"):
            argv = argv[1:]
            while argv and argv[0].startswith("-"):
                argv = argv[1:]
        else:
            return argv


def _dev_args(argv):
    """The arguments of a `dev` call (dev, bin/dev, python3 bin/dev, python3 -m devkit.cli), else None."""
    n = os.path.basename(argv[0])
    if n == "dev":
        return argv[1:]
    if _INTERP.match(n) and len(argv) > 1:
        if os.path.basename(argv[1]) == "dev":
            return argv[2:]
        if argv[1:3] in (["-m", "devkit"], ["-m", "devkit.cli"]):
            return argv[3:]
    return None


def _shell_inputs(args, cwd, bodies) -> list:
    """The scripts a shell runs: its -c string, a script file, or its input (the command's heredocs)."""
    i = 0
    while i < len(args):
        a = args[i]
        if a == "--":
            i += 1
            break
        if a.startswith("-") and not a.startswith("--") and "c" in a[1:]:
            return [args[i + 1]] if i + 1 < len(args) else []
        if a in ("-o", "+o", "-O", "+O", "--rcfile", "--init-file"):
            i += 2
            continue
        if a.startswith(("-", "+")):
            i += 1
            continue
        break
    if i < len(args):
        return [_read_small(resolve(args[i], cwd))]
    return list(bodies)


def _program(argv, cwd, bodies):
    """-> (code, args, module, in_place): the program text an interpreter runs (inline, a script file or its input)."""
    fam = re.sub(r"[0-9.]+$", "", os.path.basename(argv[0]).casefold())
    args, code, script, module, inplace, i = argv[1:], [], None, None, False, 0
    while i < len(args):
        a, nxt = args[i], args[i + 1] if i + 1 < len(args) else ""
        short = a.startswith("-") and not a.startswith("--") and len(a) > 1
        if fam in ("awk", "gawk", "mawk", "nawk"):
            if a == "-f":
                script, i = nxt, i + 2
                continue
            if a in ("-v", "-F"):
                i += 2
                continue
            if a.startswith("-"):
                i += 1
                continue
            if not code and script is None:
                code.append(a)
            i += 1
            break
        if fam in ("python", "pypy"):
            if short and a.endswith("c"):
                code.append(nxt)
                i += 2
                break
            if a == "-m":
                module, i = nxt, i + 2
                break
        elif fam in ("perl", "ruby") and short and a[-1] in "eE" or \
                a in {"node": ("-e", "--eval", "-p", "--print"), "bun": ("-e", "--eval", "-p", "--print"),
                      "nodejs": ("-e", "--eval", "-p", "--print"), "deno": ("eval",), "php": ("-r",),
                      "osascript": ("-e",), "lua": ("-e",), "rscript": ("-e",), "swift": ("-e",)}.get(fam, ()):
            code.append(nxt)
            inplace = inplace or (fam in ("perl", "ruby") and "i" in a[1:-1])
            i += 2
            continue
        if short and fam in ("perl", "ruby") and "i" in a[1:]:
            inplace = True
        if a == "-":  # the program comes from the input (a heredoc); what follows are its arguments
            script, i = a, i + 1
            break
        if a.startswith("-"):
            i += 1
            continue
        if not code and script is None:
            script, i = a, i + 1
        break
    rest = args[i:]
    if script and script != "-":
        code.append(_read_small(resolve(script, cwd)))
    elif not code and module is None:
        code += list(bodies)
    return "\n".join(code), rest, module, inplace


def protected_bash(cmd: str, cwd):
    """Deny a shell command that writes devkit's state, configuration or install, runs `dev config set
    safeguards.*`, or sets a DEVKIT_* key in a settings file (spec C11)."""
    if not cmd or not cmd.strip():
        return None
    return _Shell(cmd, cwd).run()


# --------------------------------------------------------------------------- crew members (spec F3/F4, guard side)
#
# A crew member is a subagent. devkit routes its `dev progress …` and `dev crew ask|answer|…` calls to its own lane
# only when the call is the whole command (hooks._route_subagent_progress rewrites that one command). A lane call
# anywhere else runs as Morpheus: it advances the main plan or records the developer's decision, so it is refused.
# What counts is what the shell runs (lessons L-fxom7edle07, L-fxpeihqfwzb; B-fxn17sez8cj): the command words, nested
# shells (bash -c, eval, source, xargs, find -exec, a heredoc a shell reads), the command substitutions the shell
# expands (inside double quotes too) and the program an interpreter runs when it can start a process. Text a command
# only carries is not a call: a quoted commit message, a --check note, a heredoc written to a file. Read-only crew
# commands pass anywhere; `dev crew sync` only when plugin/agents/ is in the member's step scope. This reads command
# text and stops the usual forms; an obfuscated call (a name built at run time) is for F4's call ledger (spec D3).

_CREW_LANE = frozenset({"ask", "answer", "inbox", "decide", "decisions", "mode", "delegate", "decline", "route"})
_CREW_READ = frozenset({"graph", "show", "rules", "history", "next"})
_LANE_TEXT = re.compile(r"\bdev\W{1,6}(?:progress|crew)\b")
_DEV_IN_CODE = re.compile(r"(?<![\w.-])dev[\s'\",\[\]]{1,6}(progress|crew)\b(?:[\s'\",\]]{1,6}(-{0,2}[A-Za-z][\w-]*))?")
_SPAWNS = re.compile(
    r"\bsubprocess\b|\bos\.(?:system|popen|exec\w*|spawn\w*|posix_spawn\w*)\b|\bpty\.spawn\b|\bchild_process\b|"
    r"\b(?:execSync|spawnSync|execFile\w*|spawn|exec|system|popen|proc_open|shell_exec|passthru)\s*\(|"
    r"\bIO\.popen\b|\bOpen3\b|\bProcess\.(?:spawn|exec)\b|\bdo shell script\b|\bDeno\.(?:run|Command)\b|"
    r"\bBun\.(?:spawn|\$)")
_SPAWNS_QUOTED = re.compile(r"`[^`]*`|\bqx\b|%x[\[{(]")  # backticks run a command in perl, ruby and php only
LANE_REASON = ("Run `dev progress …` and `dev crew …` as a command of its own (no `&&`, `;`, pipes, `$(…)`, `bash -c`, "
               "`env` or `timeout` around it), so devkit can route it to your lane; anywhere else it would act as "
               "Morpheus. Text that only mentions these commands (a quoted message, a heredoc written to a file) is "
               "fine, and read-only crew commands (graph, show, raci, …) work anywhere.")


def _subst(s: str, quotes: bool) -> list:
    out, i, n, q = [], 0, len(s), None
    while i < n:
        c = s[i]
        if q == "'":
            q = None if c == "'" else q
            i += 1
            continue
        if c == "\\":
            i += 2
            continue
        if quotes and q is None and c == "'":
            q = "'"
        elif quotes and c == '"':
            q = None if q == '"' else '"'
        elif quotes and q is None and c == "#" and (i == 0 or s[i - 1] in " \t\n;&|()"):
            j = s.find("\n", i)
            i = n if j < 0 else j
            continue
        elif s.startswith("$(", i):
            j, depth, qq = i + 2, 1, None
            while j < n and depth:
                d = s[j]
                if qq:
                    if d == "\\" and qq == '"':
                        j += 1
                    elif d == qq:
                        qq = None
                elif d == "\\":
                    j += 1
                elif d in "'\"":
                    qq = d
                elif d == "(":
                    depth += 1
                elif d == ")":
                    depth -= 1
                j += 1
            out.append(s[i + 2:j - 1] if depth == 0 else s[i + 2:])
            i = j
            continue
        elif c == "`":
            j = i + 1
            while j < n and s[j] != "`":
                j += 2 if s[j] == "\\" else 1
            out.append(s[i + 1:j])
            i = j + 1
            continue
        i += 1
    return out


def _expansions(cmd: str) -> list:
    """The command substitutions the shell runs: `$(…)` and backticks outside single quotes and comments (inside
    double quotes too), and in heredoc bodies whose delimiter is unquoted."""
    text, bodies = _split_heredocs(cmd)
    out = _subst(text, True)
    for body, expands in bodies:
        if expands:
            out += _subst(body, False)
    return out


def shell_calls(cmd: str, cwd, depth: int = 0):
    """Every program a shell command runs, as (argv, code): each segment's command words without prefixes or
    keywords, the commands of nested shells and of the substitutions the shell expands, and for an interpreter the
    program it runs (inline, its input, or a script outside the workspace; None for a repository's own script).
    Text the command only carries is not a call. None when the command cannot be parsed."""
    if depth > 4:
        return []
    segs = split_commands(cmd)
    if segs is None:
        return None
    bodies, out = heredoc_bodies(cmd), []
    for argv0, _ in segs:
        argv = _unwrap(argv0)
        if not argv:
            continue
        if os.path.basename(argv[0]) in ("cd", "pushd"):
            cwd = str(core.HOME) if len(argv) == 1 else cwd if argv[1] == "-" else str(resolve(argv[1], cwd))
            continue
        more = _program_calls(argv, cwd, bodies, depth)
        if more is None:
            return None
        out += more
    for text in _expansions(cmd):
        more = shell_calls(text, cwd, depth + 1)
        if more is None:
            return None
        out += more
    return out


def _program_calls(argv, cwd, bodies, depth):
    name, args = os.path.basename(argv[0]), argv[1:]
    if _INTERP.match(name) and _dev_args(argv) is None:
        return [(argv, None if _repo_script(argv, cwd) else _program(argv, cwd, bodies)[0])]
    out, texts, inners = [(argv, None)], [], []
    if name in _SHELLS:
        texts = _shell_inputs(args, cwd, bodies)
    elif name in ("source", ".") and args:
        texts = [_read_small(resolve(args[0], cwd))]
    elif name == "eval":
        texts = [" ".join(args)]
    elif name == "xargs":
        i, takes = 0, {"-I", "-n", "-P", "-L", "-d", "-E", "-s", "-a", "-J", "-R", "-S"}
        while i < len(args) and args[i].startswith("-"):
            i += 2 if args[i] in takes else 1
        inners = [_unwrap(args[i:])]
    elif name == "find":
        for k, a in enumerate(args):
            if a in ("-exec", "-execdir", "-ok", "-okdir"):
                sub = args[k + 1:]
                inners.append(_unwrap(sub[:next((j for j, x in enumerate(sub) if x in (";", "+")), len(sub))]))
    for text in texts:
        more = shell_calls(text, cwd, depth + 1) if text else []
        if more is None:
            return None
        out += more
    for inner in inners:
        if inner:
            out += _program_calls(inner, cwd, bodies, depth + 1) or []
    return out


def _crew_kind(args) -> str:
    """For the arguments of a `dev` call: 'lane' (a call devkit routes to the caller's lane), 'read' (read-only crew),
    'sync' (`dev crew sync`), 'team' (changes the team's crew or briefs a member), '' (no progress or crew call)."""
    pos = [a for a in args if not a.startswith("-")]
    if not pos or pos[0] not in ("progress", "crew"):
        return ""
    if {"-h", "--help"} & set(args):
        return "read"
    if pos[0] == "progress":
        return "lane"
    rest = args[args.index("crew") + 1:]
    sub = next((a for a in rest if not a.startswith("-")), None)
    if sub is None or sub in _CREW_READ:
        return "read"
    if sub == "raci":
        return "team" if any(a == "--set" or a.startswith("--set=") for a in rest) else "read"
    if sub == "sync":
        return "read" if "--check" in rest else "sync"
    return "lane" if sub in _CREW_LANE else "team"


def _dev_calls(argv, code) -> list:
    """The `dev progress|crew` calls of one program, as [(kind, args)]."""
    if code is not None:  # an interpreter: only a program that can start a process runs dev
        fam = re.sub(r"[0-9.]+$", "", os.path.basename(argv[0]).casefold())
        if not (_SPAWNS.search(code) or (fam in ("perl", "ruby", "php") and _SPAWNS_QUOTED.search(code))):
            return []
        found = [[m.group(1)] + ([m.group(2)] if m.group(2) else []) for m in _DEV_IN_CODE.finditer(code)]
        return [(_crew_kind(a), a) for a in found if _crew_kind(a)]
    args = _dev_args(argv)
    if args is None and argv[0][:1] in ("$", "`") and argv[1:2] in (["progress"], ["crew"]):
        args = argv[1:]  # `$D crew …`: a program the guard cannot see, called the way dev is
    kind = _crew_kind(args) if args is not None else ""
    return [(kind, args)] if kind else []


def _layers(scope) -> list:
    """A step scope as layers of globs: a flat list is one layer; a path must be in every layer (a nested member's
    scope lies inside its parent's, spec F3). [] when there is no scope."""
    if not scope:
        return []
    if all(isinstance(g, str) for g in scope):
        return [list(scope)]
    return [[g for g in layer if isinstance(g, str)] for layer in scope if layer]


def _glob_hit(path: str, g: str) -> bool:
    g = g.rstrip("/") if g not in ("/", "") else g
    return fnmatch.fnmatchcase(path, g) or fnmatch.fnmatchcase(path, g + "/**") or \
        path.startswith(g.rstrip("*").rstrip("/") + "/") or path == g


def scope_holds(path, cwd, globs) -> bool:
    """True when `path` is in one of `globs`, by the crew scope rules: a glob relative to the repository of `cwd`
    (`lib/**`, `docs/`, a file) never reaches outside it; an absolute or ~ glob names a folder anywhere, such as the
    project's plans in the handoff repository."""
    ap = os.path.normpath(os.path.join(str(cwd), str(path)))
    top = core.gitout(cwd, "rev-parse", "--show-toplevel") or str(cwd)
    rel = os.path.relpath(ap, top)
    for g in globs or []:
        if g.startswith(("/", "~")):
            ga = os.path.expanduser(g)
            if _glob_hit(ap, ga) or _glob_hit(real(ap), ga) or _glob_hit(real(ap), _real_glob(ga)):
                return True
        elif not rel.startswith("..") and _glob_hit(rel, g):
            return True
    return False


def _real_glob(g: str) -> str:
    """An absolute glob with its literal folder part resolved (/tmp/x/** → /private/tmp/x/**)."""
    parts = g.split("/")
    k = next((j for j, p in enumerate(parts) if any(ch in p for ch in "*?[")), len(parts))
    return "/".join([real("/".join(parts[:k]) or "/")] + parts[k:]) if k else g


def _dev_home(argv, cwd) -> Path:
    """The devkit checkout a `dev` call runs: bin/dev's folder (through the symlink on PATH), else devkit's home."""
    a0 = argv[1] if os.path.basename(argv[0]) != "dev" and len(argv) > 1 else argv[0]
    if os.path.basename(a0) == "dev":
        p = resolve(a0, cwd) if "/" in a0 or a0.startswith("~") else Path(real(shutil.which("dev") or a0))
        if p != UNKNOWN and p.is_file():
            return Path(real(p)).parent.parent
    return Path(real(core.DEVKIT_HOME))


def _sync_verdict(argv, cwd, scope):
    agents = _dev_home(argv, cwd) / "plugin" / "agents"
    layers = _layers(scope)
    probe = str(agents / "__any_agent__.md")  # sync rewrites and removes every generated file there
    if layers and all(scope_holds(probe, cwd, layer) for layer in layers):
        return None
    where = "; ".join(", ".join(layer) for layer in layers) or "no step scope"
    return deny(f"`dev crew sync` rewrites and removes the generated files in {tilde(agents)}/, which your step's "
                f"scope ({where}) does not hold. Ask Morpheus to add plugin/agents/** to your step (`dev crew ask "
                f"\"…\"`), or run `dev crew sync --check` and report what differs.")


def crew_shell_verdict(cmd: str, cwd, scope=None):
    """For a crew member's shell command that devkit did not route to its lane: ("deny", why) when it runs a
    `dev progress` or `dev crew` call that would act as Morpheus or change the team's crew, or `dev crew sync` that
    writes outside the member's step scope; None otherwise. `scope`: the step scope, globs or layers of globs."""
    if not cmd or not str(cmd).strip():
        return None
    calls = shell_calls(cmd, cwd or os.getcwd())
    if calls is None:  # the shell would read it another way than the tokenizer: judge the words, refuse a lane name
        return deny(LANE_REASON) if _LANE_TEXT.search(cmd) else None
    for argv, code in calls:
        for kind, args in _dev_calls(argv, code):
            if kind == "lane":
                return deny(LANE_REASON)
            if kind == "team":
                sub = next((a for a in args[1:] if not a.startswith("-")), "")
                return deny(f"`dev crew {sub}` changes the team's crew or briefs a member: Morpheus runs it. Ask him "
                            f"with `dev crew ask \"…\"` and say what should change and why.")
            if kind == "sync":
                v = _sync_verdict(argv, cwd or os.getcwd(), scope)
                if v:
                    return v
    return None


def bulk_rewrite(cmd: str, cwd=None) -> bool:
    """True when a shell command rewrites files with a regex (lesson L-fwyp0n9vzv6): sed or perl/ruby in place, or a
    program that substitutes with re.sub and writes, wherever the shell runs it. Text that mentions one is not one."""
    calls = shell_calls(cmd or "", cwd or os.getcwd()) or []
    for argv, code in calls:
        name = os.path.basename(argv[0])
        flags = [a for a in argv[1:] if a.startswith("-") and not a.startswith("--")]
        if name in ("sed", "gsed") and ("i" in "".join(f[1:] for f in flags) or
                                         any(a == "--in-place" or a.startswith("--in-place=") for a in argv[1:])):
            return True
        if re.sub(r"[0-9.]+$", "", name) in ("perl", "ruby") and any("i" in f[1:] for f in flags):
            return True
        if code and re.search(r"\bre\.subn?\(", code) and re.search(r"\.write_text\(|\.write\(|open\([^)]*[\"'][wa]",
                                                                    code):
            return True
    return False


def member_write_exempt(path, cwd, scope=None) -> bool:
    """True when a crew member may write `path` with a file tool whatever its tool level or step scope: a scratch file
    (a temp folder outside the repository it works in), or a plan of its own project in the handoff repository
    (plans/<project>/) that every layer of its step scope names. That is how a review-only member such as The Oracle
    writes the spec it was asked for."""
    if not path:
        return False
    ap = os.path.normpath(os.path.join(str(cwd), str(path)))
    top = core.gitout(cwd, "rev-parse", "--show-toplevel")
    if is_temp(ap) and not (top and is_under(Path(real(ap)), Path(real(top)))):
        return True
    pid = current_project(cwd)
    if not pid or not is_under(Path(real(ap)), Path(real(core.HANDOFF)) / "plans" / pid):
        return False
    layers = _layers(scope)
    return bool(layers) and all(scope_holds(ap, cwd, layer) for layer in layers)


def check(tool: str, tool_input: dict, cwd: str, agent: str):
    tool_input = tool_input or {}
    if tool in WRITE_TOOLS or "file_path" in tool_input or "notebook_path" in tool_input:
        path = tool_input.get("file_path") or tool_input.get("notebook_path")
        if tool not in READ_TOOLS:
            v = protected_write(path, cwd, tool_input)
            if v:
                return v
        return devkit_off(path, tool_input) or check_write_path(path, cwd, agent)
    cmd = tool_input.get("command") if isinstance(tool_input, dict) else None
    if isinstance(cmd, list):
        cmd = " ".join(shlex.quote(c) for c in cmd)
    if not isinstance(cmd, str):
        return None
    if tool == "apply_patch" or cmd.lstrip().startswith("*** Begin Patch"):
        v = protected_patch(cmd, cwd)
        if v:
            return v
        for op, path in parse_patch_paths(cmd):
            if op == "delete":
                continue
            v = check_write_path(path, cwd, agent)
            if v:
                return v
        return None
    return check_bash(cmd, cwd, agent)
