def _wrapped(n, args):
    """The command a wrapper runs, as argv: a command line it hands to a shell comes back as `sh -c <line>`, and one
    GNU parallel appends its inputs to ends with `{}` (known only when it runs). [] when it runs none."""
    takes, i, direct = _WRAP_VALUES.get(n, set()), 0, False
    while i < len(args) and args[i].startswith("-") and args[i] != "-":
        a = args[i]
        if a == "--":
            i += 1
            break
        if n in ("script", "flock") and (a in ("-c", "--command") or a.startswith("--command=")):
            line = a.split("=", 1)[1] if "=" in a else (args[i + 1] if i + 1 < len(args) else "")
            return ["sh", "-c", line] if line else []
        direct = direct or (n == "watch" and a in ("-x", "--exec"))
        i += 2 if a in takes else 1
    rest = args[i:]
    if n in ("script", "flock"):  # script [file [command …]] (BSD), flock <file> <command …>
        return rest[1:]
    if n == "watch":  # without -x, watch hands the words to `sh -c`
        return rest if direct or not rest else ["sh", "-c", " ".join(rest)]
    if n in ("parallel", "sem"):
        cut = next((k for k, x in enumerate(rest) if x in (":::", "::::", ":::+", "::::+")), len(rest))
        cmd, inputs = rest[:cut], rest[cut + 1:]
        if not cmd:  # each input is a command line; with none here, parallel reads them from its input
            return ["sh", "-c", "; ".join(inputs)] if inputs else ["sh", "-s"]
        return cmd if any("{" in x for x in cmd) else cmd + ["{}"]
    return rest


_PY_FLAGS = frozenset("uIBEsSOqbdvxRP")  # python's own flags without a value; -W and -X take one


def _dev_args(argv):
    """The arguments of a `dev` call (dev, bin/dev, python3 bin/dev, python3 -m devkit.cli, also after the
    interpreter's own flags: python3 -u -I -B …), else None."""
    n = os.path.basename(argv[0])
    if n == "dev":
        return argv[1:]
    if _INTERP.match(n) and len(argv) > 1:
        i = 1
        while i < len(argv) and argv[i].startswith("-") and argv[i] not in ("-m", "-c", "-", "--"):
            a = argv[i]
            if a in ("-W", "-X"):
                i += 2
            elif a[1:2] in ("W", "X") or set(a[1:]) <= _PY_FLAGS:
                i += 1
            else:
                break
        if i < len(argv) and os.path.basename(argv[i]) == "dev":
            return argv[i + 1:]
        if argv[i:i + 2] in (["-m", "devkit"], ["-m", "devkit.cli"]):
            return argv[i + 2:]
    return None


def _shell_inputs(args, cwd, bodies) -> list:
    """The scripts a shell runs: its -c string, a script file, or its input (the command's heredocs)."""
    i = 0
    while i < len(args):
        a = args[i]
        if a == "--":
            i += 1
            break
        if a.startswith("-") and not a.startswith("--") and "c" in a[1:]:
            return [args[i + 1]] if i + 1 < len(args) else []
        if a in ("-o", "+o", "-O", "+O", "--rcfile", "--init-file"):
            i += 2
            continue
        if a.startswith(("-", "+")):
            i += 1
            continue
        break
    if i < len(args):
        return [_read_small(resolve(args[i], cwd))]
    return list(bodies)


def _program(argv, cwd, bodies):
    """-> (code, args, module, in_place): the program text an interpreter runs (inline, a script file or its input)."""
    fam = re.sub(r"[0-9.]+$", "", os.path.basename(argv[0]).casefold())
    args, code, script, module, inplace, i = argv[1:], [], None, None, False, 0
    while i < len(args):
        a, nxt = args[i], args[i + 1] if i + 1 < len(args) else ""
        short = a.startswith("-") and not a.startswith("--") and len(a) > 1
        if fam in ("awk", "gawk", "mawk", "nawk"):
            if a == "-f":
                script, i = nxt, i + 2
                continue
            if a in ("-v", "-F"):
                i += 2
                continue
            if a.startswith("-"):
                i += 1
                continue
            if not code and script is None:
                code.append(a)
            i += 1
            break
        if fam in ("python", "pypy"):
            if short and a.endswith("c"):
                code.append(nxt)
                i += 2
                break
            if a == "-m":
                module, i = nxt, i + 2
                break
        elif fam in ("perl", "ruby") and short and a[-1] in "eE" or \
                a in {"node": ("-e", "--eval", "-p", "--print"), "bun": ("-e", "--eval", "-p", "--print"),
                      "nodejs": ("-e", "--eval", "-p", "--print"), "deno": ("eval",), "php": ("-r",),
                      "osascript": ("-e",), "lua": ("-e",), "rscript": ("-e",), "swift": ("-e",)}.get(fam, ()):
            code.append(nxt)
            inplace = inplace or (fam in ("perl", "ruby") and "i" in a[1:-1])
            i += 2
            continue
        if short and fam in ("perl", "ruby") and "i" in a[1:]:
            inplace = True
        if a == "-":  # the program comes from the input (a heredoc); what follows are its arguments
            script, i = a, i + 1
            break
        if a.startswith("-"):
            i += 1
            continue
        if not code and script is None:
            script, i = a, i + 1
        break
    rest = args[i:]
    if script and script != "-":
        code.append(_read_small(resolve(script, cwd)))
    elif not code and module is None:
        code += list(bodies)
    return "\n".join(code), rest, module, inplace


def protected_bash(cmd: str, cwd):
    """Deny a shell command that writes devkit's state, configuration or install, runs `dev config set
    safeguards.*`, or sets a DEVKIT_* key in a settings file (spec C11)."""
    if not cmd or not cmd.strip():
        return None
    return _Shell(cmd, cwd).run()


# ---- devkit's evidence functions called from an agent's own program (B1 of Seraph's review batch 3)
#
# devkit takes the developer's prompts and answers from the hooks the harness fires, checked against the session's
# transcript (progress.confirmed; for Codex the hook alone). A program an agent runs can call the same functions
# with a payload of its own: progress.on_human_prompt with a transcript the agent wrote, then use_grant, opened
# `release v26.11.4` in Seraph's repro. So a program that loads a devkit module and reaches one of these functions,
# or devkit's state writers, is a forgery attempt for every agent, the main session included. The guard judges the
# programs the shell runs, as the irreversible gate does: inline code, its input (a heredoc, a here-string, a pipe from
# echo, printf or cat), a script outside the workspace or in a temp folder, nested shells, substitutions, and the
# command lines a program hands to a process. A repository's own script (a test, run by path or by a test runner) is
# the repository's code and is not judged here; the transcript rule and progress's own checks hold for it.

_EVIDENCE_FNS = frozenset({"on_human_prompt", "on_question", "on_prompt", "confirmed", "use_grant", "take_evidence",
                           "evidence", "_keep_human", "_consume", "crew_decide", "_action_evidence",
                           "_decision_evidence", "_live_grants", "_grant_lookup"})
_EVIDENCE_COMMON = frozenset({"confirmed", "evidence"})  # common words: they count only on a devkit module
_STATE_WRITERS = frozenset({"update", "replace", "patch", "remove", "_write"})  # devkit.state's, on that module only
_EVIDENCE_TEXT = re.compile(r"\b(?:" + "|".join(sorted(_EVIDENCE_FNS - _EVIDENCE_COMMON)) + r")\b")
_DEVKIT_LOAD_TEXT = re.compile(r"\b(?:from|import)\s+devkit\b|(?:__import__|import_module)\s*\(\s*['\"]devkit\b")
_DEVKIT_MODULE_STR = re.compile(r"^devkit(?:\.\w+)*$|(?:^|/)devkit/\w+\.py$")
FORGERY_REASON = ("This program loads devkit and reaches `{fn}`, which records or uses the developer's prompts, "
                  "answers and grants. Called from an agent's program, it would forge the developer's approval (spec "
                  "C5; Seraph's B1), so no session runs it, the main session included. The hooks call it when the "
                  "harness fires them. To try it, write or run a test in the repository (tests/test_evidence.py shows "
                  "how, with its state in a temporary folder); to read records, use `dev status`, `dev crew "
                  "decisions` or `dev audit`. For a grant, ask the developer to type `grant <action> <target>`.")


def _const_str(n):
    """The text of a string constant, a sum of them or an f-string without fields; None for anything else."""
    import ast
    if isinstance(n, ast.Constant) and isinstance(n.value, str):
        return n.value
    if isinstance(n, ast.BinOp) and isinstance(n.op, ast.Add):
        a, b = _const_str(n.left), _const_str(n.right)
        return a + b if a is not None and b is not None else None
    if isinstance(n, ast.JoinedStr):
        parts = [_const_str(v) for v in n.values]
        return "".join(parts) if all(p is not None for p in parts) else None
    return None


def _devkit_module(name) -> bool:
    return bool(name) and (name == "devkit" or name.startswith("devkit."))


DECODED = "code it decodes at run time"
DECODED_REASON = ("This program runs code it decodes at run time (exec of base64, hex, zlib or marshal data), which the "
                  "guard cannot read, so it cannot tell whether it forges the developer's approval or writes devkit's "
                  "records (spec C5, C11). Write the code out in the command or a script file.")
_DECODERS = frozenset({"b64decode", "b32decode", "b85decode", "a85decode", "urlsafe_b64decode", "decodebytes",
                       "decodestring", "fromhex", "unhexlify", "a2b_base64", "a2b_hex", "decompress", "loads",
                       "decode", "rot13", "reversed"})


def _agent_file(p) -> bool:
    """A file an agent may have written for itself: outside the workspace or in a temp folder; not a repository's own
    code, which `_repo_script` leaves to its tests and review."""
    return p != UNKNOWN and p.is_file() and (not is_under(p, DEV) or is_temp(p))


def _local_module(name, dirs):
    """The agent's file that `import <name>` loads from one of `dirs` (the program's folder, its constant sys.path
    entries), or None."""
    rel = str(name or "").replace(".", "/")
    for d in dirs:
        for cand in (f"{rel}.py", f"{rel}/__init__.py", f"{rel}/__main__.py"):
            p = resolve(os.path.join(str(d), cand), str(d))
            if _agent_file(p):
                return p
    return None


def _read_call_path(n):
    """The constant path of `open(P).read()` or `Path(P).read_text()`, else None."""
    import ast
    if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and n.func.attr in ("read", "read_text",
                                                                                          "read_bytes"):
        inner = n.func.value
        if isinstance(inner, ast.Call) and getattr(inner.func, "id", getattr(inner.func, "attr", "")) in (
                "open", "Path", "PurePath", "io.open") and inner.args:
            return _const_str(inner.args[0])
    return None


def _decodes(n) -> bool:
    import ast
    return any(isinstance(x, ast.Call) and (getattr(x.func, "attr", "") or getattr(x.func, "id", "")) in _DECODERS
               for x in ast.walk(n))


def _aliases(tree) -> dict:
    import ast
    return {a.asname: a.name for n in ast.walk(tree) if isinstance(n, (ast.Import, ast.ImportFrom))
            for a in n.names if a.asname}  # `SourceFileLoader as L`: a call to L is a call to SourceFileLoader


def _loaded_files(code, cwd) -> list:
    """The agent's own files (_agent_file) a Python program loads: a module by name from its folder or a constant
    sys.path entry (import, from-import, import_module, run_module), runpy.run_path, exec(open(…).read()),
    spec_from_file_location and SourceFileLoader. A file the guard does not read is code it cannot judge."""
    import ast
    try:
        tree = ast.parse(code or "")
    except (SyntaxError, ValueError):
        return []
    dirs = [d for d in [cwd] if d] + [_const_str(n.args[-1]) for n in ast.walk(tree) if isinstance(n, ast.Call)
                                      and getattr(n.func, "attr", "") in ("insert", "append", "addsitedir")
                                      and n.args and _const_str(n.args[-1])]
    alias, out = _aliases(tree), []

    def local(name):
        p = _local_module(name, dirs) if name and not _devkit_module(name) else None
        out.extend([p] if p else [])

    def path(arg):
        p = resolve(arg, cwd) if arg else UNKNOWN
        out.extend([p] if _agent_file(p) else [])
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            for a in n.names:
                local(a.name)
        elif isinstance(n, ast.ImportFrom) and not n.level:
            local(n.module)
        elif isinstance(n, ast.Call) and n.args:
            f = n.func
            fname = alias.get(f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", ""), "")
            fname = (fname or (f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", ""))).rpartition(".")[2]
            if fname == "run_path":
                path(_const_str(n.args[0]))
            elif fname in ("spec_from_file_location", "SourceFileLoader") and len(n.args) > 1:
                path(_const_str(n.args[1]))
            elif fname in ("__import__", "import_module", "run_module"):
                local(_const_str(n.args[0]))
            elif fname in ("eval", "exec", "compile"):
                path(_read_call_path(n.args[0]))
    return list(dict.fromkeys(out))


def loaded_texts(code, cwd, depth: int = 0) -> list:
    """The text of every agent file a program loads, and of the files they load, three levels deep."""
    out = []
    for p in (_loaded_files(code, cwd) if depth < 3 else []):
        text = _read_small(p)
        out += [text] + loaded_texts(text, str(p.parent), depth + 1)
    return out


def evidence_reached(code, cwd=None, depth: int = 0) -> str:
    """The devkit evidence function (or devkit.state writer) a program reaches, or '': it loads a devkit module (import,
    from-import, __import__, importlib, a devkit file by path) and names one (an attribute, an imported name, a
    getattr, a string), or looks a name up on a devkit module at run time. The agent's own files it loads (a local
    module from its folder or a constant sys.path entry, runpy.run_path, exec(open(…).read()), spec_from_file_location)
    are judged too, three levels deep; code it decodes and runs is DECODED. Code that is not Python is judged by its
    text."""
    import ast
    if not code or not str(code).strip() or depth > 3:
        return ""
    try:
        tree = ast.parse(code)
    except (SyntaxError, ValueError):
        m = _EVIDENCE_TEXT.search(code) if _DEVKIT_LOAD_TEXT.search(code) else None
        return m.group(0) if m else ""
    loads, maybe, star, dynamic, hit = False, False, False, False, ""
    mods = {}  # local name -> the devkit module it is bound to
    alias = _aliases(tree)
    for n in ast.walk(tree):
        if isinstance(n, ast.Import):
            for a in n.names:
                if _devkit_module(a.name):
                    loads = True
                    mods[a.asname or a.name.split(".")[0]] = a.name if a.asname else "devkit"
        elif isinstance(n, ast.ImportFrom) and not n.level and _devkit_module(n.module):
            loads = True
            for a in n.names:
                if a.name == "*":
                    star = True
                elif a.name in _EVIDENCE_FNS or (n.module == "devkit.state" and a.name in _STATE_WRITERS):
                    hit = hit or a.name
                else:
                    mods[a.asname or a.name] = f"{n.module}.{a.name}"
        elif isinstance(n, ast.Constant) and isinstance(n.value, str):
            if _DEVKIT_MODULE_STR.search(n.value):
                loads = True
        elif isinstance(n, ast.Call):
            f = n.func
            fname = f.attr if isinstance(f, ast.Attribute) else getattr(f, "id", "")
            fname = alias.get(fname, fname).rpartition(".")[2]
            first = _const_str(n.args[0]) if n.args else None
            if fname in ("__import__", "import_module", "spec_from_file_location", "run_module", "run_path",
                         "SourceFileLoader"):
                arg = first if fname not in ("spec_from_file_location", "SourceFileLoader") else (
                    _const_str(n.args[1]) if len(n.args) > 1 else None)
                if arg is None:
                    maybe = True
                elif _DEVKIT_MODULE_STR.search(arg):
                    loads = True
            elif fname == "getattr" and len(n.args) > 1:
                name = _const_str(n.args[1])
                if name is None:
                    dynamic = True
                elif name in _EVIDENCE_FNS:
                    hit = hit or name
            elif fname in ("eval", "exec", "compile", "vars"):
                inner = first
                path = _read_call_path(n.args[0]) if n.args and inner is None else None
                if path:
                    continue  # the file it reads is judged below
                elif inner is None and n.args and fname != "vars" and _decodes(n.args[0]):
                    return DECODED
                elif inner is None:
                    dynamic = True
                else:
                    sub = evidence_reached(inner, cwd, depth + 1)
                    hit = hit or sub
                    loads = loads or bool(_DEVKIT_LOAD_TEXT.search(inner))
    for p in _loaded_files(code, cwd):
        sub = evidence_reached(_read_small(p), str(p.parent), depth + 1)
        if sub:
            return sub
    for n in ast.walk(tree):
        if isinstance(n, ast.Attribute):
            base = n.value.id if isinstance(n.value, ast.Name) else n.value.attr if isinstance(n.value, ast.Attribute) \
                else ""
            on = mods.get(base, "")
            if n.attr in _EVIDENCE_FNS - _EVIDENCE_COMMON or (on and n.attr in _EVIDENCE_COMMON):
                hit = hit or n.attr
            elif n.attr in _STATE_WRITERS and (on == "devkit.state" or (base == "state" and loads)):
                hit = hit or f"state.{n.attr}"
            elif n.attr in ("__dict__", "__getattribute__") and on:
                dynamic = True
        elif isinstance(n, ast.Name) and star and n.id in _EVIDENCE_FNS:
            hit = hit or n.id
        elif isinstance(n, ast.Constant) and isinstance(n.value, str) and n.value in _EVIDENCE_FNS - _EVIDENCE_COMMON:
            hit = hit or n.value
    if hit and (loads or maybe):
        return hit
    return "a name looked up at run time" if loads and dynamic else ""


def _forged_calls(text, cwd, depth=0) -> str:
    """The first evidence function an agent's program reaches in a command line, level by level, or ''. A line the
    guard cannot parse is judged by its text."""
    if depth > 4 or not text or not str(text).strip():
        return ""
    segs = split_commands(text, ops=True)
    if segs is None:
        return evidence_reached(text) if _DEVKIT_LOAD_TEXT.search(text) else ""
    bodies = heredoc_bodies(text)
    for k, (argv0, _, _, here) in enumerate(segs):
        argv = _unwrap(argv0)
        if not argv:
            continue
        name = os.path.basename(argv[0])
        if name in ("cd", "pushd"):
            cwd = str(core.HOME) if len(argv) == 1 else cwd if argv[1] == "-" else str(resolve(argv[1], cwd))
            continue
        prev = _unwrap(segs[k - 1][0]) if k and segs[k - 1][2] in ("|", "|&") else []
        fn = _forged_argv(argv, cwd, bodies, list(here), prev, depth)
        if fn:
            return fn
    for sub in _expansions(text):
        fn = _forged_calls(sub, cwd, depth + 1)
        if fn:
            return fn
    return ""


def _forged_argv(argv, cwd, bodies, here, prev, depth) -> str:
    name, args = os.path.basename(argv[0]), argv[1:]
    if _INTERP.match(name) and _dev_args(argv) is None:
        if _repo_script(argv, cwd):
            return ""
        code, _, module, _ = _program(argv, cwd, bodies)
        if not code and module is None and prev:  # it reads its program from the pipe
            code = _produced(prev, cwd)
        where = cwd
        if module and not _devkit_module(module):  # python -m <mod>: an agent's module in the folder it runs in
            p = _local_module(module, [cwd])
            code, where = (_read_small(p), str(p.parent)) if p else (code, cwd)
        script = next((resolve(a, cwd) for a in args if a.endswith(".py") and not a.startswith("-")), None)
        if script is not None and script != UNKNOWN:  # a script's own folder comes first in its sys.path
            where = str(script.parent)
        fn = evidence_reached(code, where)
        for t in ([] if fn else _code_texts(code)):
            fn = fn or _forged_calls(t, cwd, depth + 1)
        return fn
    texts, inners = [], []
    if name in _SHELLS:
        texts = _shell_inputs(args, cwd, bodies)
        if _reads_stdin(args):
            texts += here + ([_produced(prev, cwd)] if prev else [])
    elif name in ("source", ".") and args:
        texts = [_read_small(resolve(args[0], cwd))]
    elif name == "eval":
        texts = [" ".join(args)]
    elif name == "xargs":
        i, takes = 0, {"-I", "-n", "-P", "-L", "-d", "-E", "-s", "-a", "-J", "-R", "-S"}
        while i < len(args) and args[i].startswith("-"):
            i += 2 if args[i] in takes else 1
        inners = [_unwrap(args[i:])]
    elif name == "find":
        for k, a in enumerate(args):
            if a in ("-exec", "-execdir", "-ok", "-okdir"):
                sub = args[k + 1:]
                inners.append(_unwrap(sub[:next((j for j, x in enumerate(sub) if x in (";", "+")), len(sub))]))
    for t in texts:
        fn = _forged_calls(t, cwd, depth + 1)
        if fn:
            return fn
    for inner in inners:
        fn = _forged_argv(inner, cwd, bodies, [], [], depth + 1) if inner and depth < 4 else ""
        if fn:
            return fn
    return ""


def evidence_forgery(cmd: str, cwd):
    """("deny", why) when a program the shell command runs loads devkit and reaches an evidence function or devkit's
    state writers (B1 of Seraph's review batch 3); None otherwise."""
    if not cmd or not cmd.strip():
        return None
    fn = _forged_calls(cmd, cwd or os.getcwd())
    if fn == DECODED:
        return deny(DECODED_REASON)
    return deny(FORGERY_REASON.format(fn=fn)) if fn else None


# --------------------------------------------------------------------------- crew members (spec F3/F4, guard side)
#
# A crew member is a subagent. devkit routes its `dev progress …` and `dev crew ask|answer|…` calls to its own lane
# only when the call is the whole command (hooks._route_subagent_progress rewrites that one command). A lane call
# anywhere else runs as Morpheus: it advances the main plan or records the developer's decision, so it is refused.
# What counts is what the shell runs (lessons L-fxom7edle07, L-fxpeihqfwzb; B-fxn17sez8cj): the command words, nested
# shells (bash -c, eval, source, xargs, find -exec, a heredoc a shell reads), the command substitutions the shell
# expands (inside double quotes too) and the program an interpreter runs when it can start a process. Text a command
# only carries is not a call: a quoted commit message, a --check note, a heredoc written to a file. Read-only crew
# commands pass anywhere; `dev crew sync` only when plugin/agents/ is in the member's step scope. This reads command
# text and stops the usual forms; an obfuscated call (a name built at run time) is for F4's call ledger (spec D3).

