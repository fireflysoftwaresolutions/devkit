def _branch_cfg():
    b = core.CFG.get("branches") or {}
    return tuple(b.get("types") or BRANCH_TYPES), tuple(b.get("forbidden_words") or FORBIDDEN_BRANCH_WORDS)


def branch_violation(name: str):
    """Reason when a branch name breaks the GitOps naming standard, else None."""
    if not name or name in PERMANENT_BRANCHES or name.startswith(("refs/tags/", "tags/")) or name == "HEAD":
        return None
    name = name.removeprefix("refs/heads/")
    types, forbidden = _branch_cfg()
    example = "feat/PROJ-142-invoice-export, fix/login-timeout, release/26.11.4, integration/payments"
    head, _, rest = name.partition("/")
    rename = f"Rename it: `git branch -m {name} <type>/<topic>`" if name else ""
    first = re.split(r"[_.-]", head.lower())[0]
    if first in forbidden:
        return (f"Branch `{name}` is prefixed with a tool/agent or throwaway marker (`{first}`). Branch names describe "
                f"the change, not who made it: `<type>/<ticket>-<topic>` with type in {'|'.join(types)} "
                f"(e.g. {example}). {rename}")
    if head not in types or not rest:
        return (f"Branch `{name}` does not follow `<type>/<ticket>-<topic>` with type in {'|'.join(types)} "
                f"(e.g. {example}). {rename}")
    if re.search(r"(^|[-_/])[0-9a-f]{6,}$", rest) and not re.search(r"\d+\.\d+", rest):
        return (f"Branch `{name}` ends in a random/generated id. Use a short descriptive kebab-case topic. {rename}")
    if not re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*(/[a-z0-9][a-z0-9._-]*)?$", rest) or rest.lower() != rest and \
            not re.match(r"^[A-Z][A-Z0-9]+-\d+", rest):
        return (f"Branch `{name}`: use lowercase kebab-case after the type (an optional ticket key like PROJ-142 may be "
                f"uppercase). {rename}")
    if len(name) > 60:
        return f"Branch `{name}` is too long (max 60 characters). {rename}"
    return None


def deny(reason):
    return ("deny", reason)


# --------------------------------------------------------------------------- path rules

UNKNOWN = Path("/__devkit_unknown__")


def resolve(path, cwd) -> Path:
    """Absolute real path, or UNKNOWN when it depends on shell state the hook cannot see ($VAR, $(…), `…`)."""
    p = os.path.expanduser(os.path.expandvars(str(path)))
    if "$" in p or "`" in p:
        return UNKNOWN
    if not os.path.isabs(p):
        if cwd is None or str(cwd) == str(UNKNOWN):
            return UNKNOWN
        p = os.path.join(cwd, p)
    return Path(real(p))


def allowed_tops() -> set:
    tops = set(RESERVED_TOP) | core.owners()
    try:
        tops |= {e.name.lower() for e in os.scandir(DEV) if e.is_dir()}
    except OSError:
        pass
    return tops


def layout_violation(p: Path, creating_dir=False):
    """Reason string when `p` breaks the ~/Development layout, else None."""
    if p == UNKNOWN or not is_under(p, DEV) or real(p) == real(DEV):
        return None
    rel = Path(real(p)).relative_to(real(DEV)).parts
    if len(rel) == 1 and not creating_dir and not rel[0].startswith("."):
        if not (Path(real(DEV)) / rel[0]).is_dir():
            return f"Files do not go directly in {tilde(DEV)} ({rel[0]}). " + LAYOUT_HINT
    top = rel[0].lower()
    if top not in allowed_tops() and not top.startswith(".") and "." not in top:
        return (f"`{tilde(DEV)}/{rel[0]}` is not a GitHub owner folder you belong to, nor _local. "
                f"Sibling copies like `<repo>-pr12` or `<repo>-copy` are not allowed. " + LAYOUT_HINT)
    return None


GENERATED = {"PROJECTS.md", "TASKS.md", "ACTIVITY.md", "registry.json"}


def current_project(cwd):
    """Project id of the session's working directory, or None for portfolio-level sessions."""
    if not cwd or str(cwd) == str(UNKNOWN):
        return None
    top = core.gitout(cwd, "rev-parse", "--show-toplevel")
    if not top or is_temp(top) or real(top) == real(core.HANDOFF):
        return None
    from .registry import main_of
    main = main_of(Path(top)) or Path(top)
    return core.project_identity(main, core.gitout(main, "config", "--get", "remote.origin.url"))[0]


def initiative_members(slug: str) -> list:
    f = core.HANDOFF / "initiatives" / slug / "README.md"
    if not f.exists():
        return []
    from . import notes
    return notes.summarize(f.read_text())["projects"]


def handoff_violation(rel: str, cwd, envs=frozenset()):
    """Isolation in the handoff repo: a project session writes only its own note, plans and initiatives."""
    if rel.startswith("policies/"):
        return (f"`{rel}` is a recorded delivery policy, versioned with who and why. Change it with "
                f"`dev delivery apply --set key=value --why \"…\"`.")
    if rel.startswith("lessons/"):
        return (f"`{rel}` is a lesson, versioned with who and why. Use `dev lesson add|recur|prevent|retire …`.")
    if rel.startswith(("items/", "sessions/", "presence/")):
        return (f"`{rel}` is managed by devkit so that versions, locks, history and attribution stay correct. Use "
                f"`dev task add|start|done|edit|move|cancel --why …` for work items and `dev handoff --log \"…\"` "
                f"for the session log.")
    if rel in GENERATED or rel.startswith("log/"):
        return (f"`{rel}` is generated by `dev sync` from the notes; edit the project or initiative note instead "
                f"(`dev task`, `dev note set`, `dev handoff --edit`).")
    if "DEVKIT_CROSS_PROJECT" in envs or os.environ.get("DEVKIT_CROSS_PROJECT"):
        return None
    pid = current_project(cwd)
    if not pid:
        return None  # portfolio-level session (~/Development, the handoff repo itself)
    if rel.startswith("projects/"):
        target = rel[len("projects/"):].removesuffix(".md")
        if target != pid:
            return (f"This session works on `{pid}`; it must not change `{target}`'s handoff note. Record cross-project "
                    f"facts in a shared initiative (`dev initiative ls`) or tell the user what the other project needs.")
    elif rel.startswith("plans/"):
        if not rel[len("plans/"):].startswith(pid + "/"):
            return f"Plans of this session go to plans/{pid}/ — not to another project's plans."
    elif rel.startswith("initiatives/"):
        slug = rel.split("/")[1] if rel.count("/") >= 1 else ""
        if slug and pid not in initiative_members(slug):
            return (f"`{pid}` is not a member of initiative `{slug}`. Only member projects update it; ask the user "
                    f"to add it (`dev initiative add {slug} {pid}`) if it should be.")
    return None


def check_write_path(path, cwd, agent):
    if not path:
        return None
    p = resolve(path, cwd)
    if p == UNKNOWN or str(p).startswith("/dev/"):
        return None
    if is_under(p, core.HANDOFF):
        v = handoff_violation(str(Path(real(p)).relative_to(real(core.HANDOFF))), cwd)
        return deny(v) if v else None
    if is_temp(p) or any(is_under(p, r) for r in CONFIG_ROOTS):
        return None
    if p.parent == Path(real(HOME)) and p.name.startswith("."):
        return None  # dotfiles such as ~/.zshrc
    if is_under(p, DEV):
        v = layout_violation(p)
        if v:
            return deny(v)
        if BACKUP_RE.search(p.name) and not p.name.startswith("."):
            return deny(f"Do not create backup copies ({p.name}); git already keeps history. Edit the file in "
                        f"place, or put throwaway copies in a temp dir.")
        return None
    reason = (f"Writes outside {tilde(DEV)}, temp and agent-config dirs are blocked by the devkit guard "
              f"({tilde(p)}). Scratch/temporary files belong in your session scratchpad or {tilde(core.TMP_ROOT)}; "
              f"project files in {tilde(DEV)}/<owner>/<repo>.")
    if agent == "claude":
        return ("ask", reason + " Only continue if the user explicitly asked for this path.")
    return deny(reason + " If the user explicitly asked for this path, tell them the guard blocked it.")


# --------------------------------------------------------------------------- bash parsing

def _newlines_to_semicolons(cmd: str) -> str:
    out, q = [], None
    i = 0
    while i < len(cmd):
        ch = cmd[i]
        if q:
            if ch == "\\" and q == '"' and i + 1 < len(cmd):
                out.append(cmd[i:i + 2])
                i += 2
                continue
            if ch == q:
                q = None
        elif ch in ("'", '"'):
            q = ch
        elif ch == "\n":
            ch = ";"
        out.append(ch)
        i += 1
    return "".join(out)


HEREDOC_RE = re.compile(r"<<-?\s*(['\"]?)([A-Za-z_][A-Za-z0-9_]*)\1")


def strip_heredocs(cmd: str) -> str:
    """Drop heredoc bodies (they are data, not commands): keep the line with `<<EOF`, skip to the terminator."""
    lines, out, i = cmd.split("\n"), [], 0
    while i < len(lines):
        ln = lines[i]
        out.append(ln)
        m = HEREDOC_RE.search(ln)
        i += 1
        if m:
            term = m.group(2)
            while i < len(lines) and lines[i].strip() != term:
                i += 1
            i += 1  # skip the terminator line
    return "\n".join(out)


def split_commands(cmd: str):
    """-> list of (argv, redirect_targets). None when the command cannot be tokenised."""
    cmd = strip_heredocs(cmd)
    try:
        lex = shlex.shlex(_newlines_to_semicolons(cmd), posix=True, punctuation_chars=";&|()<>")
        lex.whitespace_split = True
        lex.commenters = ""
        tokens = list(lex)
    except ValueError:
        return None
    segs, argv, redirs, expect_redir = [], [], [], False
    for k, t in enumerate(tokens):
        nxt = tokens[k + 1] if k + 1 < len(tokens) else ""
        if t.isdigit() and nxt[:1] in ("<", ">"):
            continue  # file-descriptor prefix: the 2 in 2>&1 / 2>file
        if t and set(t) <= set("<>&-") and "&" in t and ("<" in t or ">" in t):
            if nxt.isdigit() or nxt == "-":
                expect_redir = None  # fd duplication: skip the fd number
            else:
                expect_redir = ">" in t
            continue
        if t and set(t) <= set(";&|()"):
            if argv or redirs:
                segs.append((argv, redirs))
            argv, redirs = [], []
            continue
        if t and set(t) <= set("<>"):
            expect_redir = ">" in t
            if not expect_redir:
                expect_redir = None  # input redirect: skip next token
            continue
        if expect_redir is not False:
            if expect_redir:
                redirs.append(t)
            expect_redir = False
            continue
        argv.append(t)
    if argv or redirs:
        segs.append((argv, redirs))
    return segs


def _strip_prefix(argv):
    i = 0
    while i < len(argv):
        a = argv[i]
        if re.match(r"^[A-Za-z_][A-Za-z0-9_]*=", a):
            i += 1
        elif os.path.basename(a) in PREFIX_CMDS:
            i += 1
            while i < len(argv) and argv[i].startswith("-"):
                i += 1
        else:
            break
    return argv[i:]


def _git_split(argv):
    """git [-C dir] [-c k=v] <sub> args -> (dir_or_None, sub, args)."""
    i, cdir = 1, None
    while i < len(argv):
        a = argv[i]
        if a == "-C" and i + 1 < len(argv):
            cdir, i = argv[i + 1], i + 2
        elif a in ("-c", "--git-dir", "--work-tree", "--namespace") and i + 1 < len(argv):
            i += 2
        elif a.startswith("-"):
            i += 1
        else:
            return cdir, a, argv[i + 1:]
    return cdir, None, []


def _positionals(args, value_opts):
    pos, i = [], 0
    while i < len(args):
        a = args[i]
        if a == "--":
            pos += args[i + 1:]
            break
        if a.startswith("-"):
            if a in value_opts and "=" not in a:
                i += 1
        else:
            pos.append(a)
        i += 1
    return pos


def _opt_value(args, opts):
    """Value of the first of `opts` in args (`-b name`, `--create=name`)."""
    for i, a in enumerate(args):
        if a in opts and i + 1 < len(args):
            return args[i + 1]
        for o in opts:
            if o.startswith("--") and a.startswith(o + "="):
                return a.split("=", 1)[1]
    return None


def _main_of(path: Path):
    from .registry import main_of
    p = path
    while not p.exists() and p != p.parent:
        p = p.parent
    return main_of(p)


def check_worktree_add(args, cwd):
    pos = _positionals(args, {"-b", "-B", "--reason", "--orphan"})
    if not pos:
        return None
    target = resolve(pos[0], cwd)
    if target == UNKNOWN or is_under(target, WT_ROOT) or is_temp(target):
        return None
    return deny(f"Raw `git worktree add {pos[0]}` would create an unmanaged worktree at {tilde(target)}. "
                f"Use `dev wt new <branch>` (it places it in {tilde(WT_ROOT)}/<project path>/<branch>, reuses "
                f"dependencies and registers it for cleanup), or your harness's own worktree tool. Only create a "
                f"worktree when the user asked for one or parallel work really needs it.")


def check_clone(url, dest, cwd):
    src = core.clone_source(url)
    name = (src[0].rsplit("/", 1)[-1] if src else os.path.basename(url.rstrip("/"))).removesuffix(".git")
    target = resolve(dest or name, cwd)
    if target == UNKNOWN or is_temp(target):
        return None
    if src:
        canon = core.canonical_path(src[0])
        if real(target).lower() == real(canon).lower():
            return None
        return deny(f"Clone to the canonical path instead: `dev clone {url}` → {tilde(canon)}. "
                    f"For a throwaway look at the code, clone into a temp dir.")
    if is_under(target, LOCAL):
        return None
    return deny("Clone repos with `dev clone <url>` (it places them by host/owner/repo), or into a temp dir for a "
                "throwaway look. " + LAYOUT_HINT)


RAW_FS_HINT = ("Use `dev rm <paths>` instead: it moves them to the Trash with a manifest (`dev rm --undo` restores "
               "them), refuses files that are open or hold unsaved work, stages tracked deletions like `git rm`, and "
               "tells you the exact flag when you really mean it. To bypass, prefix the command with DEVKIT_RAW_FS=1.")


def _is_build_output(t: Path) -> bool:
    from .gc import ARTEFACTS
    return t.name in ARTEFACTS or t.name in ("__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache", "coverage",
                                              ".gradle", ".parcel-cache", ".cache")


def steer_rm(args, cwd, envs=frozenset()):
    """Plain rm outside scratch areas goes through `dev rm` (recoverable, checked)."""
    if "DEVKIT_RAW_FS" in envs:
        return None
    targets = [a for a in args if not a.startswith("-") or a == "-"]
    if not targets:
        return None
    for a in targets:
        t = resolve(a, cwd)
        if t == UNKNOWN:  # depends on shell state ($VAR, cd $X) the guard cannot see: not flagged, like other rules
            continue
        if _is_build_output(Path(a.rstrip("/"))) or is_temp(t) or _is_build_output(t):
            continue
        return deny(f"`rm {a}` deletes permanently. " + RAW_FS_HINT)
    return None


def check_rm(args, cwd, envs=frozenset()):
    flags = [a for a in args if a.startswith("-")]
    recursive = any(a in ("--recursive",) or (not a.startswith("--") and ("r" in a or "R" in a)) for a in flags)
    if not recursive:
        return steer_rm(args, cwd, envs)
    for a in [a for a in args if not a.startswith("-")]:
        if a in ("*", "./*", ".", "..") and cwd and str(cwd) != str(UNKNOWN) and \
                any(real(cwd) == real(p) for p in [HOME, DEV] + list(_owner_dirs())):
            return deny(f"`rm -r {a}` in {tilde(cwd)} would wipe the workspace. Remove specific paths only.")
        t = resolve(a, cwd)
        if t == UNKNOWN:
            continue
        if any(real(t) == real(p) for p in PROTECTED_RM):
            return deny(f"Refusing to recursively delete protected path {tilde(t)}.")
        if is_temp(t):
            continue  # scratch area: throwaway clones and repos may be deleted
        if t.name == ".git":
            return deny("Refusing to delete a .git directory (this destroys the repository history).")
        if is_under(t, DEV) and real(t) != real(DEV):
            rel = Path(real(t)).relative_to(real(DEV)).parts
            if len(rel) == 1 and not rel[0].startswith("."):
                return deny(f"Refusing to delete the whole folder {tilde(t)}. Ask the user.")
            if (t / ".git").is_file():
                return deny(f"{tilde(t)} is a git worktree: remove it with `dev wt rm {tilde(t)}` (checks for "
                            f"unpushed work and keeps git metadata consistent), not rm -rf.")
            if (t / ".git").is_dir():
                return deny(f"{tilde(t)} is a repository checkout. Deleting it can lose unpushed work; ask the user.")
    return steer_rm(args, cwd, envs)


def _owner_dirs():
    try:
        return [Path(e.path) for e in os.scandir(DEV) if e.is_dir()]
    except OSError:
        return []


def _attribution(text: str):
    low = text.lower()
    for pat in ATTRIBUTION:
        if pat in low:
            return deny("User policy: no AI attribution in commits, tags or PRs. Remove the "
                        f"“{pat}” line (no Co-Authored-By/Generated-with trailers) and retry.")
    return None


def check_git(argv, cwd, full_segment, envs=frozenset(), pending=None):
    cdir, sub, args = _git_split(argv)
    gcwd = str(resolve(cdir, cwd)) if cdir else cwd
    if gcwd == str(UNKNOWN):
        gcwd = None
    if sub == "add" and pending is not None and gcwd:  # checked with the commit that follows in the same command
        pending.append((gcwd, list(args)))
    if sub == "worktree" and args[:1] == ["add"]:
        nb = _opt_value(args[1:], ("-b", "-B"))
        v = branch_violation(nb) if nb else None
        if v:
            return deny(v)
        return check_worktree_add(args[1:], gcwd)
    if sub in ("checkout", "switch"):
        nb = _opt_value(args, ("-b", "-B", "-c", "-C", "--create", "--force-create", "--orphan"))
        v = branch_violation(nb) if nb else None
        if v:
            return deny(v)
    if sub == "branch":
        info = {"-d", "-D", "--delete", "-l", "--list", "-a", "--all", "-r", "--remotes", "-v", "-vv", "--verbose",
                "--show-current", "--contains", "--no-contains", "--merged", "--no-merged", "-u",
                "--set-upstream-to", "--unset-upstream", "--edit-description", "--format", "--sort", "--points-at",
                "-c", "-C", "--copy"}
        flags = {a.split("=")[0] for a in args if a.startswith("-")}
        pos = _positionals(args, {"-u", "--set-upstream-to", "--format", "--sort", "--contains", "--no-contains",
                                  "--merged", "--no-merged", "--points-at"})
        if flags & {"-m", "-M", "--move"} and pos:
            v = branch_violation(pos[-1])
            if v:
                return deny(v)
        elif pos and not (flags & info):
            v = branch_violation(pos[0])
            if v:
                return deny(v)
    if sub == "clone":
        pos = _positionals(args, {"-b", "--branch", "-o", "--origin", "--depth", "--reference", "-c", "--config",
                                  "--filter", "-j", "--jobs", "--separate-git-dir", "--template", "-u",
                                  "--upload-pack", "--shallow-since", "--shallow-exclude", "--server-option"})
        if pos:
            return check_clone(pos[0], pos[1] if len(pos) > 1 else None, gcwd)
    if sub == "push":
        force = any(a in ("--force", "-f") or (re.match(r"^-[a-zA-Z]*f[a-zA-Z]*$", a) and not a.startswith("--"))
                    for a in args) or any(a.startswith("+") for a in args if not a.startswith("-"))
        lease = any(a.startswith(("--force-with-lease", "--force-if-includes")) for a in args)
        targets_default = any(re.search(r"(^|:|/)(main|master)$", a) for a in args if not a.startswith("-"))
        if force:
            return deny("Plain force-push is blocked. Use `git push --force-with-lease` on your own feature branch.")
        if lease and targets_default:
            return deny("Never force-push main/master.")
        if not any(a in ("--tags", "--delete", "-d", "--mirror") for a in args):
            pos = _positionals(args, {"-o", "--push-option", "--repo", "--receive-pack", "--exec"})
            refspecs = pos[1:] if pos else []
            dsts = [r.lstrip("+").split(":")[-1] for r in refspecs] if refspecs else \
                [core.gitout(gcwd, "branch", "--show-current")]
            for d in dsts:
                if d in ("HEAD", "") or d.startswith("v") and re.match(r"^v?\d", d):
                    d = core.gitout(gcwd, "branch", "--show-current") if d in ("HEAD", "") else ""
                v = branch_violation(d) if d else None
                if v:
                    return deny(v.replace("Rename it:", "Rename it before pushing:"))
        return check_push_budget(gcwd, args, envs)
    if sub == "clean" and any(re.match(r"^-[a-zA-Z]*f", a) or a == "--force" for a in args) and \
            not any(re.match(r"^-[a-zA-Z]*n", a) or a == "--dry-run" for a in args) and \
            "DEVKIT_RAW_FS" not in envs and gcwd and not is_temp(Path(gcwd)):
        rc, out, _ = core.git(gcwd, "clean", "-n", *[a for a in args if not re.match(r"^-[a-zA-Z]*f", a) and a != "--force"])
        n = len([ln for ln in out.splitlines() if ln.strip()]) if rc == 0 else 0
        if n:
            return deny(f"`git clean -f` would permanently delete {n} untracked path(s) in {tilde(gcwd)} (untracked work "
                        f"cannot be recovered from git). Review them with `git clean -n`, then remove them with "
                        f"`dev rm --discard <paths>` (recoverable from the Trash). To bypass, prefix with DEVKIT_RAW_FS=1.")
    if sub == "clean" and any(re.match(r"^-[a-zA-Z]*[xX]", a) for a in args):
        return deny("`git clean -x/-X` deletes ignored files too (.env, local config, caches). Use `git clean -fd` "
                    "for untracked files only, or remove specific paths.")
    if sub == "reset" and "--hard" in args:
        rc, out, _ = core.git(gcwd, "status", "--porcelain", "--untracked-files=no")
        n = len([ln for ln in out.splitlines() if ln.strip()]) if rc == 0 else 0
        if n:
            return deny(f"`git reset --hard` would discard {n} uncommitted change(s) in {tilde(gcwd)}. Commit them "
                        f"to a WIP branch first, or ask the user.")
    if sub == "stash" and (not args or args[0] in ("push", "pop", "apply", "save", "-u", "--include-untracked",
                                                    "-k", "-m", "--keep-index")):
        return deny("`git stash` is shared by every worktree of this repository, so another session can pop your "
                    "changes. Use `dev commit --wip` (a WIP commit on your branch; `dev commit --unwip` undoes it).")
    if sub == "tag" and gcwd and "DEVKIT_TAG_ANY" not in envs and \
            not any(a in ("-d", "--delete", "-l", "--list", "-v", "--verify", "-n") or a.startswith("--contains")
                    for a in args):
        names = [a for a in args if not a.startswith("-")]
        if names:
            pid = current_project(gcwd)
            if pid:
                from .delivery import tag_violation
                v = tag_violation(pid, names[0])
                if v:
                    return deny(v + " (DEVKIT_TAG_ANY=1 bypasses.)")
    if sub in ("commit", "tag", "merge", "notes"):
        a = _attribution(full_segment)
        if a:
            return a
        if sub == "commit" and gcwd and not os.environ.get("DEVKIT_SKIP_SECRET_SCAN"):
            from .security import staged_secrets
            commit_all = any(a == "--all" or (a.startswith("-") and not a.startswith("--") and "a" in a[1:])
                             for a in args)
            found = staged_secrets(gcwd, adds=[a for c, a in pending or [] if c == gcwd], all_tracked=commit_all)
            if found:
                return deny("gitleaks found secret-like content in the staged changes: " + "; ".join(found[:5]) +
                            ". Remove it and load it from the environment or the secret manager (rotate it if it was "
                            "ever pushed). A false positive: add a `gitleaks:allow` comment on that line or an entry "
                            "in .gitleaksignore, then commit again.")
        if sub == "commit":
            for i, x in enumerate(args):
                if x in ("-F", "--file") and i + 1 < len(args):
                    f = resolve(args[i + 1], gcwd)
                    try:
                        if f.is_file() and f.stat().st_size < 200_000:
                            return _attribution(f.read_text(errors="ignore"))
                    except OSError:
                        pass
    if sub == "init":
        pos = _positionals(args, {"-b", "--initial-branch", "--template", "--separate-git-dir", "--object-format"})
        target = resolve(pos[0], gcwd) if pos else Path(real(gcwd))
        v = layout_violation(target, creating_dir=True)
        if v:
            return deny(v)
    return None


PUSH_WINDOW_S, PUSH_LIMIT = 3600, 2


def check_push_budget(cwd, args, envs):
    """Block CI loops: the 3rd push of the same branch within an hour needs a local green run first."""
    import json
    import time
    top = core.gitout(cwd, "rev-parse", "--show-toplevel")
    if not top:
        return None
    pos = _positionals(args, {"-o", "--push-option", "--repo", "--receive-pack", "--exec"})
    branch = (pos[1].split(":")[-1] if len(pos) > 1 else core.gitout(cwd, "branch", "--show-current")) or "HEAD"
    main = core.gitout(cwd, "rev-parse", "--path-format=absolute", "--git-common-dir") or top
    key = f"{main}|{branch}"
    f = core.STATE / "ci-pushes.json"
    try:
        data = json.loads(f.read_text()) if f.exists() else {}
    except (OSError, ValueError):
        data = {}
    now = time.time()
    recent = [t for t in data.get(key, []) if now - t < PUSH_WINDOW_S]
    if len(recent) >= PUSH_LIMIT and "DEVKIT_LOCAL_CI_PASSED" not in envs:
        return deny(f"This would be push #{len(recent) + 1} of `{branch}` in the last hour, and every push runs CI "
                    f"again. Stop the push-and-see loop: read the failing log (`gh run view --log-failed`), run what "
                    f"CI runs locally (`dev ci` shows the exact commands), fix, and push once. If the full local "
                    f"suite has just passed in this session, prefix the push with DEVKIT_LOCAL_CI_PASSED=1.")
    recent.append(now)
    data = {k: [t for t in v if now - t < PUSH_WINDOW_S] for k, v in data.items()}
    data[key] = recent
    try:
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(json.dumps({k: v for k, v in data.items() if v}))
    except OSError:
        pass
    return None


PIPE_GATE = re.compile(r"\|(?!\|)[^|&;\n]*&&\s*(?:[A-Z_]+=\S*\s+)*(?:git\s+(?:-C\s+\S+\s+)?(?:commit|push|tag)\b|"
                       r"dev\s+(?:commit|push|release)\b|gh\s+(?:pr\s+(?:create|merge)|release\s+create)\b)")


def check_bash(cmd: str, cwd: str, agent: str):
    if not cmd or not cmd.strip():
        return None
    if PIPE_GATE.search(cmd) and "pipefail" not in cmd and "DEVKIT_PIPE_OK" not in cmd:
        return deny("This commits, pushes or tags after a pipeline (`… | … && git commit`): the `&&` sees the exit "
                    "code of the pipe's last command, so a failing check before the pipe still lets it run. Run the "
                    "check without the pipe, use `set -o pipefail;` first, or test its output "
                    "(`out=$(… | tail -1); [ \"$out\" = OK ] && …`). Lesson: gate on the real result.")
    segs = split_commands(cmd)
    if segs is None:
        return _attribution(cmd) if re.search(r"\b(git|gh)\b", cmd) else None
    ecwd = cwd or os.getcwd()
    raw_segments = re.split(r"&&|\|\||;|\n|\|", cmd)
    pending_adds = []
    for idx, (argv0, redirs) in enumerate(segs):
        envs = frozenset(a.split("=", 1)[0] for a in argv0[:len(argv0) - len(_strip_prefix(argv0))] if "=" in a)
        argv = _strip_prefix(argv0)
        for r in redirs:
            v = check_write_path(r, ecwd, agent)
            if v:
                return v
        if not argv:
            continue
        name = os.path.basename(argv[0])
        seg_text = " ".join(argv)
        if name == "cd":
            if len(argv) > 1 and argv[1] != "-":
                ecwd = str(resolve(argv[1], ecwd))
            continue
        if name == "pushd" and len(argv) > 1:
            ecwd = str(resolve(argv[1], ecwd))
            continue
        res = None
        if name == "git":
            res = check_git(argv, ecwd, seg_text + " " + (raw_segments[idx] if idx < len(raw_segments) else ""), envs,
                            pending_adds)
        elif name == "gh":
            sub = argv[1:3]
            if sub == ["repo", "clone"]:
                pos = _positionals(argv[3:], {"-u", "--upstream-remote-name"})
                if pos:
                    res = check_clone(pos[0], pos[1] if len(pos) > 1 else None, ecwd)
            elif argv[1:3] == ["pr", "merge"] and "--admin" in argv:
                res = deny("`gh pr merge --admin` bypasses branch protection and required reviews. Get the checks and "
                           "reviews green, then `dev pr merge`.")
            elif argv[1:3] in (["pr", "merge"], ["release", "create"]) and "DEVKIT_RAW_GH" not in envs:
                what = "dev pr merge" if argv[2] == "merge" else "dev release"
                res = deny(f"Use `{what}`: it checks CI, reviews, conflicts and the delivery policy (tag format, "
                           f"CHANGELOG section) and writes the merge or release text by the template. "
                           f"To bypass, prefix with DEVKIT_RAW_GH=1.")
            elif argv[1:3] == ["run", "rerun"] and "DEVKIT_FLAKY" not in envs:
                res = deny("Re-running CI without a change repeats the same failure and costs a full CI cycle. Read the "
                           "log (`gh run view <id> --log-failed`), reproduce it locally (`dev ci` lists the exact "
                           "commands), fix, run the local suite, then push once. Only if you have evidence the failure "
                           "is a known flaky test (record it in the handoff note), prefix the command with "
                           "DEVKIT_FLAKY=1.")
            elif argv[1:3] == ["pr", "create"] and _opt_value(argv[3:], ("--head", "-H")) and \
                    branch_violation(_opt_value(argv[3:], ("--head", "-H"))):
                res = deny(branch_violation(_opt_value(argv[3:], ("--head", "-H"))))
            elif argv[1:2] and argv[1] in ("pr", "issue", "release", "api"):
                res = _attribution(cmd)
        elif name == "dev" and len(argv) > 1 and argv[1] in ("task", "note", "handoff", "initiative"):
            res = check_dev_cross(argv[1:], ecwd, envs)
        elif name in ("rm", "unlink"):
            res = check_rm(argv[1:], ecwd, envs) if name == "rm" else steer_rm(argv[1:], ecwd, envs)
        elif name == "find" and ("-delete" in argv or any(x in argv for x in ("-exec", "-execdir")) and
                                 any(os.path.basename(x) in ("rm", "unlink") for x in argv)) and \
                "DEVKIT_RAW_FS" not in envs:
            roots = [a for a in argv[1:] if not a.startswith("-") and a not in ("(", ")", "!")][:1] or ["."]
            t = resolve(roots[0], ecwd)
            if t == UNKNOWN or not is_temp(t):
                res = deny("`find … -delete` / `-exec rm` deletes permanently whatever matches. List the matches with "
                           "`dev find <pattern>`, then delete them with `dev rm <paths>` (recoverable). To bypass, "
                           "prefix the command with DEVKIT_RAW_FS=1.")
        elif name == "xargs" and any(os.path.basename(x) in ("rm", "unlink") for x in argv[1:]) and \
                "DEVKIT_RAW_FS" not in envs and not is_temp(Path(ecwd)):
            res = deny("`xargs rm` deletes permanently whatever it is fed. " + RAW_FS_HINT)
        elif name in ("mkdir", "touch"):
            for a in [a for a in argv[1:] if not a.startswith("-")]:
                v = layout_violation(resolve(a, ecwd), creating_dir=(name == "mkdir"))
                if v:
                    res = deny(v)
                    break
        elif name in ("cp", "mv", "rsync", "ditto"):
            pos = [a for a in argv[1:] if not a.startswith("-")]
            if len(pos) >= 2:
                dest = resolve(pos[-1], ecwd)
                v = layout_violation(dest, creating_dir=True)
                safe = any(a in ("-n", "-i", "--no-clobber", "--interactive") or
                           (a.startswith("-") and not a.startswith("--") and ("n" in a or "i" in a))
                           for a in argv[1:] if a.startswith("-"))
                if not v and name in ("cp", "mv") and not safe and "DEVKIT_RAW_FS" not in envs and \
                        dest != UNKNOWN and dest.is_file() and not is_temp(dest):
                    v = (f"`{name}` would overwrite {tilde(dest)} without a copy. Use `dev {name}` (refuses to overwrite; "
                         f"with --force the old version goes to the Trash and `dev rm --undo` restores it), or add -n. "
                         f"To bypass, prefix the command with DEVKIT_RAW_FS=1.")
                if v:
                    res = deny(v)
                elif dest != UNKNOWN and not dest.is_dir() and BACKUP_RE.search(dest.name) and is_under(dest, DEV):
                    res = deny(f"Do not create backup copies ({dest.name}); git already keeps history.")
        if res:
            return res
    return None


def check_dev_cross(args, cwd, envs):
    """`dev task|note|handoff -p X / -i S` from inside another project."""
    if "DEVKIT_CROSS_PROJECT" in envs or os.environ.get("DEVKIT_CROSS_PROJECT"):
        return None
    pid = current_project(cwd)
    if not pid:
        return None
    proj = _opt_value(args, ("-p", "--project"))
    init = _opt_value(args, ("-i", "--initiative"))
    if args[:1] == ["initiative"] and len(args) > 2 and args[1] in ("add", "rm", "new"):
        return deny("Changing an initiative's membership is a portfolio decision: ask the user, or run it from "
                    f"{tilde(core.DEV)} (a portfolio-level session).")
    if proj and proj.lower() != pid:
        return deny(f"This session works on `{pid}`; `-p {proj}` would edit another project's handoff. Only do it if "
                    f"the user asked, from that project's folder or a portfolio session.")
    if init and pid not in initiative_members(init):
        return deny(f"`{pid}` is not a member of initiative `{init}`.")
    return None


def parse_patch_paths(patch: str):
    """apply_patch envelope -> [(op, path)] for Add/Update/Delete/Move."""
    out = []
    for ln in patch.splitlines():
        m = re.match(r"^\*\*\* (Add|Update|Delete) File: (.+)$", ln.strip())
        if m:
            out.append((m.group(1).lower(), m.group(2).strip()))
        m = re.match(r"^\*\*\* Move to: (.+)$", ln.strip())
        if m:
            out.append(("add", m.group(1).strip()))
    return out


DEVKIT_OFF = [
    (re.compile(r'"disableAllHooks"\s*:\s*true'), "disables every hook, including devkit's context, guard and canary"),
    (re.compile(r'"devkit@firefly-devkit"\s*:\s*false'), "disables the devkit plugin"),
    (re.compile(r'(^|\n)\s*(codex_)?hooks\s*=\s*false'), "turns Codex hooks off"),
]


def devkit_off(path: str, tool_input: dict):
    """Agent settings files (project or user) must not switch devkit off; that is a decision for devkit's config."""
    if not path:
        return None
    p = Path(path)
    is_settings = (p.parent.name == ".claude" and p.name in ("settings.json", "settings.local.json")) or \
        (p.parent.name == ".codex" and p.name in ("config.toml", "hooks.json"))
    if not is_settings:
        return None
    texts = [tool_input.get("content") or "", tool_input.get("new_string") or ""]
    texts += [e.get("new_string") or "" for e in tool_input.get("edits") or [] if isinstance(e, dict)]
    for rx, what in DEVKIT_OFF:
        if any(rx.search(x) for x in texts):
            return ("deny", f"This change {what} for `{core.tilde(path)}`. devkit must stay active in every Claude and "
                            f"Codex session. If it really should be off, change devkit's configuration "
                            f"(~/.config/devkit/config.json, `dev config`) — ask the developer.")
    return None


def check(tool: str, tool_input: dict, cwd: str, agent: str):
    tool_input = tool_input or {}
    if tool in WRITE_TOOLS or "file_path" in tool_input or "notebook_path" in tool_input:
        path = tool_input.get("file_path") or tool_input.get("notebook_path")
        return devkit_off(path, tool_input) or check_write_path(path, cwd, agent)
    cmd = tool_input.get("command") if isinstance(tool_input, dict) else None
    if isinstance(cmd, list):
        cmd = " ".join(shlex.quote(c) for c in cmd)
    if not isinstance(cmd, str):
        return None
    if tool == "apply_patch" or cmd.lstrip().startswith("*** Begin Patch"):
        for op, path in parse_patch_paths(cmd):
            if op == "delete":
                continue
            v = check_write_path(path, cwd, agent)
            if v:
                return v
        return None
    return check_bash(cmd, cwd, agent)
