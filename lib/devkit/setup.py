def plugin_copy_stale(cache_root: Path, src: Path = None) -> bool:
    """True when the agent's installed copy of the devkit plugin differs from its source: this checkout's plugin/
    folder for Claude Code, the generated Codex copy (build_codex_plugin) for Codex. Both agents install a
    snapshot, and devkit's version does not change between commits."""
    import filecmp
    src = src or DEVKIT_HOME / "plugin"

    def version_key(p: Path):  # 26.11.10 is newer than 26.11.2: compare numbers, not text
        return [(0, int(x), "") if x.isdigit() else (1, 0, x) for x in re.split(r"[.\-+]", p.name)]
    copies = sorted((c for c in cache_root.glob("*") if c.is_dir()), key=version_key) if cache_root.exists() else []
    if not copies:
        return True
    dst = copies[-1]

    def differs(a: Path, b: Path) -> bool:
        cmp = filecmp.dircmp(a, b, ignore=[".git", ".DS_Store", "__pycache__"])
        if cmp.left_only or cmp.diff_files or cmp.funny_files:
            return True
        _, mismatch, errors = filecmp.cmpfiles(a, b, cmp.common_files, shallow=False)
        return bool(mismatch or errors) or any(differs(a / d, b / d) for d in cmp.common_dirs)

    return differs(src, dst)


