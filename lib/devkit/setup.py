def doctor() -> int:
    print(ui.banner("doctor"))
    results = []

    def check(group, name, ok, detail="", fix=""):
        results.append((group, name, ok, detail, fix))

    tools = ["git", "gh", "python3", "node", "npm", "pnpm", "uv", "java", "mvn", "gradle", "php", "composer",
             "jdtls", "pyright", "typescript-language-server", "intelephense", "ng", "docker", "colima", "jq", "rg",
             "fzf", "claude", "codex"]
    missing = [t for t in tools if not core.have(t)]
    check("Toolchain", "required tools", not missing, f"{len(tools) - len(missing)}/{len(tools)} present"
          + (f"; missing: {', '.join(missing)}" if missing else ""), "run ./install.sh (Brewfile + npm globals)")
    rc, out, err = sh(["gh", "auth", "status"], timeout=20)
    check("GitHub", "gh authenticated", rc == 0, (out + err).split("\n")[1].strip() if rc == 0 else err[:120],
          "gh auth login -s repo,read:org,workflow,gist")
    u = core.gh_user()
    name, email = core.sh(["git", "config", "--global", "user.name"])[1], core.sh(["git", "config", "--global", "user.email"])[1]
    want_email = u.get("email") or (f"{u.get('id')}+{u.get('login')}@users.noreply.github.com" if u else "")
    check("GitHub", "git identity = gh identity", bool(u) and name == (u.get("name") or u.get("login")) and email == want_email,
          f"{name} <{email}>", "dev install --only git")
    helper = core.sh(["git", "config", "--global", "--get-all", "credential.https://github.com.helper"])[1]
    check("GitHub", "git uses gh credentials", "gh auth git-credential" in helper, helper.splitlines()[-1] if helper else "unset",
          "gh auth setup-git")
    exc = core.sh(["git", "config", "--global", "core.excludesFile"])[1]
    check("GitHub", "global gitignore", exc == str(CONF / "git" / "ignore"), tilde(exc) if exc else "unset", "dev install --only git")

    check("Workspace", "dev on PATH", shutil.which("dev") is not None, shutil.which("dev") or "missing", "dev install --only cli")
    check("Workspace", "shell integration", ZSHRC.exists() and BLOCK_START in ZSHRC.read_text(), tilde(ZSHRC), "dev install --only cli")
    check("Workspace", "config file", CONFIG_FILE.exists(), tilde(CONFIG_FILE), "dev install --only config")
    hrem = core.gitout(HANDOFF, "remote", "get-url", "origin")
    check("Workspace", "handoff repo", (HANDOFF / ".git").exists() and core.handoff_repo() in hrem,
          f"{tilde(HANDOFF)} → {hrem or 'no remote'}", "dev install --only handoff")
    ahead = core.gitout(HANDOFF, "rev-list", "--count", "@{u}..HEAD")
    check("Workspace", "handoff pushed", ahead in ("0", ""), f"{ahead or '?'} commit(s) not pushed", "dev sync")
    from . import registry
    mains, _, issues = registry.discover()
    def _canon_ok(m):
        remote = core.gitout(m, "config", "--get", "remote.origin.url")
        return core.real(core.canonical_path(core.project_identity(m, remote)[0])) == core.real(m)
    layout = [m for m in mains if not _canon_ok(m)]
    check("Workspace", "canonical layout", not layout, f"{len(mains)} repos; " +
          (f"{len(layout)} not at their canonical path: {', '.join(tilde(m) for m in layout)}" if layout else "all in place"),
          "dev adopt <path> (when no sessions are open in it)")

    for target in (CLAUDE_HOME / "CLAUDE.md", CODEX_HOME / "AGENTS.md"):
        ok = target.exists() and GENERATED_MARK in target.read_text()[:200]
        check("Agents", f"{tilde(target)}", ok, "generated from devkit" if ok else "missing or hand-written",
              "dev install --only instructions")
    managed = read_json(STATE / "skills-managed.json", []) or []
    for home in (CLAUDE_HOME / "skills", AGENTS_HOME / "skills"):
        broken = [n for n in managed if not (home / n / "SKILL.md").exists()]
        check("Agents", f"skills in {tilde(home)}", managed and not broken, f"{len(managed) - len(broken)}/{len(managed)} linked",
              "dev install --only skills")

    s = read_json(CLAUDE_HOME / "settings.json", {}) or {}
    check("Claude", "bypassPermissions default", (s.get("permissions") or {}).get("defaultMode") == "bypassPermissions",
          (s.get("permissions") or {}).get("defaultMode", "unset"), "dev install --only claude")
    att = s.get("attribution") or {}
    check("Claude", "no attribution", att.get("commit") == "" and att.get("pr") == "", json.dumps(att), "dev install --only claude")
    events = {e for e, gs in (s.get("hooks") or {}).items() for g in gs for h in g.get("hooks", []) if is_devkit_hook(h)}
    check("Claude", "devkit hooks", {"SessionStart", "SessionEnd", "PreToolUse", "Stop"} <= events, ", ".join(sorted(events)),
          "dev install --only claude")
    want = load_conf("claude/plugins.json")
    _, listed, _ = sh(["claude", "plugin", "list"], timeout=60) if core.have("claude") else (1, "", "")
    blocks = {b.split("\n")[0].strip("❯ ").strip(): b for b in re.split(r"\n\s*(?=❯ )", listed)}
    bad = [p for p in want["plugins"] if p not in blocks or "enabled" not in blocks[p] or "disabled" in blocks[p]]
    check("Claude", "plugins", not bad, f"{len(want['plugins']) - len(bad)}/{len(want['plugins'])} enabled"
          + (f"; missing: {', '.join(bad)}" if bad else ""), "dev install --only claude")
    _, mcp_out, _ = sh(["claude", "mcp", "list"], timeout=90) if core.have("claude") else (1, "", "")
    miss = [n for n in want.get("mcp", {}) if not re.search(rf"^{re.escape(n)}:", mcp_out, re.M)]
    check("Claude", "MCP servers", not miss, ", ".join(want.get("mcp", {})) + (f"; missing {miss}" if miss else ""),
          "dev install --only claude")

    if core.have("codex"):
        from .codexrpc import CodexError, CodexRPC
        cw = load_conf("codex/config.json")
        try:
            with CodexRPC() as rpc:
                cfg = rpc.read().get("config", {})
                bad = {k: cfg.get(k) for k, v in cw["settings"].items() if cfg.get(k) != v}
                check("Codex", "approval/sandbox", not bad, ", ".join(f"{k}={cfg.get(k)}" for k in cw["settings"]),
                      "dev install --only codex")
                hs = [h for h in rpc.hooks(HOME) if str(h.get("sourcePath")) == str(CODEX_HOME / "hooks.json")]
                st = {h["eventName"]: h["trustStatus"] for h in hs}
                check("Codex", "devkit hooks trusted", hs and all(v == "trusted" for v in st.values()),
                      ", ".join(f"{k}:{v}" for k, v in st.items()) or "none", "dev install --only codex")
                mcps = set((cfg.get("mcp_servers") or {}).keys())
                wantm = set(load_conf("codex/plugins.json").get("mcp", {}))
                check("Codex", "MCP servers", wantm <= mcps, ", ".join(sorted(wantm & mcps)) +
                      (f"; missing {sorted(wantm - mcps)}" if wantm - mcps else ""), "dev install --only codex")
        except CodexError as e:
            check("Codex", "app-server", False, str(e), "codex doctor")
        _, listed, _ = sh(["codex", "plugin", "list"], timeout=120)
        wantp = load_conf("codex/plugins.json")["plugins"]
        bad = [p for p in wantp if not any(ln.startswith(p + " ") and "installed, enabled" in ln for ln in listed.splitlines())]
        check("Codex", "plugins", not bad, f"{len(wantp) - len(bad)}/{len(wantp)} enabled" +
              (f"; missing: {', '.join(bad)}" if bad else ""), "dev install --only codex")

    rc, out, _ = sh(["colima", "status"], timeout=20)
    check("Docker", "colima VM", rc == 0, "running" if rc == 0 else "stopped", "dev docker up")
    rc, out, _ = sh(["docker", "compose", "version", "--short"], timeout=20)
    check("Docker", "compose plugin", rc == 0, out or "not found", "dev install --only docker")

    loaded = sh(["launchctl", "print", f"gui/{os.getuid()}/{LAUNCHD_LABEL}"])[0] == 0
    last = read_json(STATE / "last-sync.json", {}) or {}
    check("Automation", "launchd sync job", loaded, f"last run {core.ago(last.get('ts'))}" if last else "never ran",
          "dev install --only launchd")
    from . import canary
    sm = canary.summary(7)
    tot = sum(t for _, t in sm.values())
    okc = sum(o for o, _ in sm.values())
    check("Automation", "instruction canary (7d)", tot == 0 or okc * 100 // tot >= 90,
          canary.summary_line(7), "`dev canary` lists deviations; check ~/.claude/CLAUDE.md and ~/.codex/AGENTS.md")
    st = os.statvfs(str(HOME))
    free_gb = st.f_bavail * st.f_frsize / 1024 ** 3
    check("Automation", "free disk", free_gb > 20, f"{free_gb:.0f} GB free", "dev gc --apply")

    group = None
    fails = 0
    for g, name, ok, detail, fix in results:
        if g != group:
            print(ui.section(g))
            group = g
        mark = ui.OK if ok else ui.FAIL
        print(f"  {mark} {name:<34} {ui.dim(detail)}")
        if not ok:
            fails += 1
            print(f"      {ui.ARROW} {fix}")
    print()
    print(f"  {ui.OK if not fails else ui.FAIL} {len(results) - fails}/{len(results)} checks passed")
    return 1 if fails else 0
