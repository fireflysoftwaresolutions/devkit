def ensure_config():
    step("devkit configuration")
    cfg = read_json(CONFIG_FILE, None)
    if cfg is None:
        user = core.gh_user().get("login", "")
        cfg = {"dev_root": "~/Development", "github_user": user,
               "handoff_repo": f"{user}/handoff" if user else "", "gc": {"auto": True}, "sync": {"push": True}}
        CONFIG_FILE.parent.mkdir(parents=True, exist_ok=True)
        CONFIG_FILE.write_text(json.dumps(cfg, indent=2) + "\n")
        done(f"created {tilde(CONFIG_FILE)} (handoff repo: {cfg['handoff_repo'] or 'unset'})")
    else:
        done(f"{tilde(CONFIG_FILE)} · handoff repo {core.handoff_repo()} · root {tilde(DEV)}")
    for d in (DEV, WT_ROOT, TMP_ROOT, LOCAL, STATE / "logs"):
        d.mkdir(parents=True, exist_ok=True)
    done(f"workspace folders: {tilde(DEV)}/{{<owner>/<repo>, _local, .worktrees, .tmp, {HANDOFF.name}}}")


def install_cli():
    step("dev command and shell integration")
    bindir = HOME / ".local" / "bin"
    bindir.mkdir(parents=True, exist_ok=True)
    link = bindir / "dev"
    target = DEVKIT_HOME / "bin" / "dev"
    if link.is_symlink() or link.exists():
        if link.resolve() != target.resolve():
            backup(link) if not link.is_symlink() else None
            link.unlink()
    if not link.exists():
        link.symlink_to(target)
    done(f"{tilde(link)} → {tilde(target)}")
    block = f'{BLOCK_START}\n[ -f "{DEVKIT_HOME}/shell/devkit.zsh" ] && source "{DEVKIT_HOME}/shell/devkit.zsh"\n{BLOCK_END}\n'
    text = ZSHRC.read_text() if ZSHRC.exists() else ""
    if BLOCK_START in text:
        new = re.sub(re.escape(BLOCK_START) + r".*?" + re.escape(BLOCK_END) + r"\n?", block, text, flags=re.S)
    else:
        new = text.rstrip("\n") + "\n\n" + block
    if new != text:
        backup(ZSHRC)
        ZSHRC.write_text(new)
    done(f"{tilde(ZSHRC)} sources shell/devkit.zsh (dcd, dwt, completion, Docker env)")


def setup_git():
    step("Git identity from GitHub CLI")
    f = STATE / "cache" / "gh-user.json"
    if f.exists():
        f.unlink()
    u = core.gh_user()
    if not u.get("login"):
        fail("gh is not logged in — run `gh auth login -s repo,read:org,workflow,gist` and re-run `dev install`")
        return
    name = u.get("name") or u["login"]
    email = u.get("email") or f"{u['id']}+{u['login']}@users.noreply.github.com"
    sh(["git", "config", "--global", "user.name", name])
    sh(["git", "config", "--global", "user.email", email])
    done(f"user.name / user.email = {name} <{email}>")
    rc, _, err = sh(["gh", "auth", "setup-git"], timeout=30)
    done("gh is git's credential helper for github.com") if rc == 0 else fail(f"gh auth setup-git: {err}")
    inc = str(CONF / "git" / "gitconfig")
    _, includes, _ = sh(["git", "config", "--global", "--get-all", "include.path"])
    if inc not in includes.splitlines():
        sh(["git", "config", "--global", "--add", "include.path", inc])
    sh(["git", "config", "--global", "core.excludesFile", str(CONF / "git" / "ignore")])
    done("shared git defaults included; global ignore covers agent artefacts (.claude/worktrees, …)")


def setup_handoff():
    step(f"Handoff repository ({core.handoff_repo()} → {tilde(HANDOFF)})")
    repo = core.handoff_repo()
    if not repo:
        fail("no handoff_repo configured")
        return
    HANDOFF.mkdir(parents=True, exist_ok=True)
    tpl = DEVKIT_HOME / "templates" / "handoff"
    if not (HANDOFF / ".git").exists():
        rc, _, _ = sh(["gh", "repo", "view", repo, "--json", "name"], timeout=30)
        if rc == 0 and not any(HANDOFF.iterdir()):
            HANDOFF.rmdir()
            sh(["gh", "repo", "clone", repo, str(HANDOFF)], timeout=120)
            done(f"cloned {repo}")
        else:
            core.git(HANDOFF, "init", "-q", "-b", "main")
            for f in tpl.iterdir():
                if not (HANDOFF / f.name).exists():
                    shutil.copy2(f, HANDOFF / f.name)
            (HANDOFF / "projects").mkdir(exist_ok=True)
            (HANDOFF / "log").mkdir(exist_ok=True)
            if rc != 0:
                rc2, out, err = sh(["gh", "repo", "create", repo, "--private", "--description",
                                    "Personal map of active projects, handoff notes and activity (managed by devkit)"],
                                   timeout=60)
                done(f"created private GitHub repo {repo}") if rc2 == 0 else fail(f"gh repo create: {err}")
            core.git(HANDOFF, "remote", "add", "origin", f"https://github.com/{repo}.git")
            if rc == 0:
                core.git(HANDOFF, "fetch", "-q", "origin", timeout=120)
                core.git(HANDOFF, "reset", "-q", "--soft", "origin/main")
            core.git(HANDOFF, "add", "-A")
            core.git(HANDOFF, "commit", "-q", "-m", "Initialise handoff repository")
            rc3, _, err = core.git(HANDOFF, "push", "-q", "-u", "origin", "main", timeout=120)
            done("initialised and pushed") if rc3 == 0 else fail(f"push failed: {err}")
    else:
        for f in tpl.iterdir():
            if not (HANDOFF / f.name).exists():
                shutil.copy2(f, HANDOFF / f.name)
        remote = core.gitout(HANDOFF, "remote", "get-url", "origin")
        done(f"present · origin {remote or 'none'}")


