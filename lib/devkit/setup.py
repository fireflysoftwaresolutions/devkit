# --------------------------------------------------------------------------- helpers

def render(text: str) -> str:
    return (text.replace("{{DEVKIT}}", str(DEVKIT_HOME)).replace("{{HOME}}", str(HOME))
            .replace("{{DEV}}", str(DEV)).replace("{{UID}}", str(os.getuid())))


def load_conf(name: str):
    return json.loads(render((CONF / name).read_text()))


def backup(path: Path):
    if path.exists():
        d = STATE / "backups"
        d.mkdir(parents=True, exist_ok=True)
        shutil.copy2(path, d / f"{path.name}.{time.strftime('%Y%m%d-%H%M%S')}")


def step(title):
    print(f"\n{ui.bold(ui.cyan('▸'))} {ui.bold(title)}")


def done(msg):
    print(f"  {ui.OK} {msg}")


def note(msg):
    print(f"  {ui.WARN} {msg}")


def fail(msg):
    print(f"  {ui.FAIL} {msg}")


def is_devkit_hook(h: dict) -> bool:
    return "devkit" in str(h.get("command", "")) and "/bin/dev" in str(h.get("command", ""))


def merge_hooks(current: dict, ours: dict) -> dict:
    """Replace devkit's own hook handlers, keep everyone else's."""
    out = {}
    for event in set(current) | set(ours):
        groups = []
        for g in current.get(event, []) or []:
            kept = [h for h in g.get("hooks", []) if not is_devkit_hook(h)]
            if kept:
                groups.append(dict(g, hooks=kept))
        groups += ours.get(event, [])
        if groups:
            out[event] = groups
    return out


