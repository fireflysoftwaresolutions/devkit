def render(text: str) -> str:
    """Fill a config template. {{DEVKIT}} is the copy the hooks run (core.runtime_home: the pinned install), also when
    this code runs from a checkout, so no setting written here ever points at the checkout once devkit is pinned."""
    return (text.replace("{{DEVKIT}}", str(core.runtime_home())).replace("{{HOME}}", str(HOME))
            .replace("{{DEV}}", str(DEV)).replace("{{UID}}", str(os.getuid())))


def load_conf(name: str):
    """A devkit config file, with the values the user chose in `dev setup` (config.json) applied."""
    data = json.loads(render((CONF / name).read_text()))
    if name == "claude/settings.json":
        cc = CFG["claude"]
        data.setdefault("permissions", {})["defaultMode"] = cc.get("default_mode", "bypassPermissions")
        if data["permissions"]["defaultMode"] != "bypassPermissions":
            data.pop("skipDangerousModePermissionPrompt", None)
        if not cc.get("fast_mode_per_session", True):
            data.pop("fastModePerSessionOptIn", None)
        for key, env in (("subagent_model", "CLAUDE_CODE_SUBAGENT_MODEL"), ("subagent_effort", "CLAUDE_CODE_SUBAGENT_EFFORT")):
            if cc.get(key):  # empty = subagents inherit the session model (the vendor default; recommended)
                data.setdefault("env", {})[env] = cc[key]
    elif name == "codex/config.json":
        cx = CFG["codex"]
        data["settings"]["approval_policy"] = cx.get("approval_policy", "never")
        data["settings"]["sandbox_mode"] = cx.get("sandbox_mode", "danger-full-access")
        if cx.get("max_subagent_threads") is not None:
            data["upsert"].setdefault("agents", {})["max_concurrent_threads_per_session"] = cx["max_subagent_threads"]
        if cx.get("profiles") is False:
            data["profiles"] = {}
        elif isinstance(cx.get("profiles"), dict):
            data["profiles"] = {**data.get("profiles", {}), **cx["profiles"]}
        for key, field in (("subagent_model", "model"), ("subagent_effort", "model_reasoning_effort")):
            if cx.get(key):
                data["upsert"].setdefault("agents", {})[f"default_subagent_{'model' if field == 'model' else 'reasoning_effort'}"] = cx[key]
    return data


def backup(path: Path, keep: int = 10):
    """Timestamped copy in ~/.local/state/devkit/backups; keeps the newest `keep` per file. A copy can hold MCP tokens
    (config.toml) or account state (~/.claude.json), so the folder is the owner's alone (0700) and each copy is
    created 0600, never through a link already there; a second copy in the same second is named `-1`, `-2`, so it
    never replaces the first. -> the copy, or None when there is no file."""
    if not path.exists():
        return None
    d = STATE / "backups"
    d.mkdir(parents=True, exist_ok=True)
    os.chmod(d, 0o700)  # nosemgrep: python.lang.security.audit.insecure-file-permissions.insecure-file-permissions (0700 is owner-only: this tightens the backups folder)
    stamp = time.strftime('%Y%m%d-%H%M%S')
    for n in range(1000):
        dest = d / f"{path.name}.{stamp}{f'-{n}' if n else ''}"
        try:
            fd = os.open(dest, os.O_WRONLY | os.O_CREAT | os.O_EXCL | os.O_NOFOLLOW, 0o600)
        except FileExistsError:
            continue
        with os.fdopen(fd, "wb") as out, open(path, "rb") as src:
            shutil.copyfileobj(src, out)
        break
    else:
        raise OSError(f"no free backup name for {path.name} in {d}")
    olds = sorted(d.glob(f"{path.name}.*"))
    for o in olds[:-keep]:
        o.unlink()
    return dest


_QUIET = [False]


class quiet_mode:
    """`with quiet_mode(True):` silences step/done/note output (used by `dev config repair` and hooks)."""

    def __init__(self, on=True):
        self.on, self.prev = on, None

    def __enter__(self):
        self.prev, _QUIET[0] = _QUIET[0], self.on

    def __exit__(self, *exc):
        _QUIET[0] = self.prev


