def is_devkit_hook(h: dict) -> bool:
    return "devkit" in str(h.get("command", "")) and "/bin/dev" in str(h.get("command", ""))


def merge_hooks(current: dict, ours: dict) -> dict:
    """Replace devkit's own hook handlers, keep everyone else's."""
    out = {}
    for event in set(current) | set(ours):
        groups = []
        for g in current.get(event, []) or []:
            kept = [h for h in g.get("hooks", []) if not is_devkit_hook(h)]
            if kept:
                groups.append(dict(g, hooks=kept))
        groups += ours.get(event, [])
        if groups:
            out[event] = groups
    return out


