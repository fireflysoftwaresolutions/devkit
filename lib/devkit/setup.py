def local_skills(home: Path) -> dict:
    """devkit's own shared skills under <home>/agents/skills -> {name: directory}. The folder may be missing: git keeps
    no empty folder, so a fresh clone or a release archive has none until a skill is added there."""
    root = home / "agents" / "skills"
    if not root.is_dir():
        return {}
    return {d.name: d for d in sorted(root.iterdir()) if (d / "SKILL.md").exists()}


def _install_skills():
    step("Skills (shared by Claude Code and Codex)")
    from . import ext
    manifest = {"sources": ext.effective_skill_sources()}  # skills.json, then the dev ext overlay
    wanted = local_skills(DEVKIT_HOME)  # name -> directory to link
    only = {}  # name -> the agents that get it (default: both)
    groups = set((core.CFG.get("skills") or {}).get("groups") or [])
    for src in manifest["sources"]:
        if src.get("group") and src["group"] not in groups and "all" not in groups:
            continue
        try:
            root = _fetch_source(src)
        except RuntimeError as e:
            fail(str(e))
            continue
        for name, rel in src["skills"].items():
            s = root / rel
            if not (s / "SKILL.md").exists():
                fail(f"{name}: SKILL.md missing in {src['repo']}@{src['ref'][:12]}/{rel}")
                continue
            out = SKILLS_SHARE / name
            try:  # the folder is deleted next: it must sit right inside the shared skills folder, links and `..`
                inside = out.resolve().parent == SKILLS_SHARE.resolve()  # resolved (`..` is devkit's install)
            except (OSError, ValueError, RuntimeError):  # a NUL in the name, a link loop (RuntimeError on 3.9)
                inside = False
            # and one folder name, never a path: `x/../kept-skill` resolves inside too, to another skill's folder
            inside = inside and name not in (".", "..") and Path(name).name == name
            if not inside:
                fail(f"{name!r} from {src['repo']}: not a folder name inside {tilde(SKILLS_SHARE)}, so it is skipped "
                     f"and nothing is deleted; rename the skill in skills.json, on a branch of the devkit checkout")
                continue
            if out.exists():
                shutil.rmtree(out)
            shutil.copytree(s, out, symlinks=True)
            (out / ".devkit-source").write_text(f"{src['repo']}@{src['ref']} {rel} license={src.get('license')}\n")
            if name == "impeccable":  # its launcher would download the engine at its first run, inside a session
                install_impeccable_engine(out, src["repo"])
            wanted[name] = out
            if src.get("agents"):  # e.g. a Claude plugin's skill given to Codex only, so Claude has no duplicate
                only[name] = set(src["agents"])
    pw = SKILLS_SHARE / "playwright-cli"  # installed by the packages step from `playwright-cli install --skills`
    if (pw / "SKILL.md").exists():
        wanted["playwright-cli"] = pw
    managed_f = STATE / "skills-managed.json"
    previous = set(read_json(managed_f, []) or [])  # a list, or {name: [agents]} since 26.11.0
    for agent, home in (("claude", CLAUDE_HOME / "skills"), ("codex", AGENTS_HOME / "skills")):
        if not agent_on(agent):  # a turned-off agent gets no skill links (remove_agent takes devkit's out)
            continue
        home.mkdir(parents=True, exist_ok=True)
        mine = {n: tg for n, tg in wanted.items() if agent in only.get(n, {"claude", "codex"})}
        for name in previous - set(mine):
            link = home / name
            if link.is_symlink() and str(os.readlink(link)).startswith(str(SKILLS_SHARE)):
                link.unlink()
        for name, target in mine.items():
            link = home / name
            if link.is_symlink():
                if Path(os.readlink(link)) == target:
                    continue
                link.unlink()
            elif link.exists():
                note(f"{tilde(link)} exists and is not managed by devkit — left untouched")
                continue
            link.symlink_to(target)
    managed_f.write_text(json.dumps({n: sorted(only.get(n, {"claude", "codex"})) for n in sorted(wanted)}))
    both = [n for n in wanted if n not in only]
    extra = "; " + ", ".join(f"{n} → {'/'.join(sorted(a))} only" for n, a in sorted(only.items())) if only else ""
    done(f"{len(both)} skills linked into {tilde(CLAUDE_HOME / 'skills')} and {tilde(AGENTS_HOME / 'skills')}{extra}")
    print("    " + ui.dim(", ".join(sorted(wanted))))


def write_claude_settings(include_hooks=True):
    """Merge devkit's managed keys into ~/.claude/settings.json (other keys untouched). -> whether it changed. A copy
    older than the pinned release writes nothing (core.older_copy_skip)."""
    f = CLAUDE_HOME / "settings.json"
    if core.older_copy_skip(tilde(f)):
        return False
    cur = read_json(f, {}) or {}
    frag = load_conf("claude/settings.json")
    plugins = load_conf("claude/plugins.json")
    new = core.deep_merge(cur, {k: v for k, v in frag.items() if k != "hooks"})
    new.pop("includeCoAuthoredBy", None)  # deprecated since Claude Code 2.0.62; `attribution` replaces it
    new["hooks"] = merge_hooks(cur.get("hooks") or {}, frag.get("hooks") or {} if include_hooks else {})
    if not new["hooks"]:
        new.pop("hooks")
    ep = dict(new.get("enabledPlugins") or {})
    from . import ext
    on, off = ext.effective_claude_plugins(ext.team(), ext.user_layer())  # team default, then the dev ext overlay
    for p in on:
        ep[p] = True
    for p in off:
        ep[p] = False
    for p in ext.retired_plugin_keys("claude"):  # retired from the team default (dev ext): its key goes too
        ep.pop(p, None)
    new["enabledPlugins"] = ep
    sl = cur.get("statusLine") or {}
    mine = "hook statusline" in str(sl.get("command") or "")
    if (core.CFG.get("claude") or {}).get("statusline", True) and (not sl or mine):
        # devkit's status line records Claude's usage windows (doctor, dashboard); a status line of yours is kept
        new["statusLine"] = {"type": "command", "command": f"'{core.runtime_home()}/bin/dev' hook statusline --agent claude",
                             "padding": 0}
    elif mine and not (core.CFG.get("claude") or {}).get("statusline", True):
        new.pop("statusLine", None)
    if new != cur:
        backup(f)
        f.parent.mkdir(parents=True, exist_ok=True)
        tmp = f.with_suffix(".json.devkit-tmp")
        tmp.write_text(json.dumps(new, indent=2, ensure_ascii=False) + "\n")
        os.replace(tmp, f)
    return new != cur


