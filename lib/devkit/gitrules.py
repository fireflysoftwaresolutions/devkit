"""devkit's own git naming and message rules, which `dev branch`, `dev commit`, `dev push` and `dev release`
check for the commands they run.

    branch_violation(name) -> str | None                  why a branch name breaks `<type>/<ticket>-<topic>`
    attribution_problem(text) -> str | None               why a message carries AI attribution
    commit_problem(top, message, *, all_tracked, adds)    attribution, then gitleaks on what the commit will hold
"""
from __future__ import annotations

import re

from . import core
from .shellparse import code_span

ATTRIBUTION = ["co-authored-by: claude", "co-authored-by: codex", "co-authored-by: chatgpt", "co-authored-by: openai",
               "co-authored-by: anthropic", "noreply@anthropic.com", "noreply@openai.com",
               "co-authored-by: copilot", "co-authored-by: github copilot", "co-authored-by: gemini",
               "co-authored-by: cursor", "cursoragent@cursor.com", "copilot@github.com",
               "generated with [claude code]", "generated with claude code", "generated with codex",
               "generated by claude", "generated by codex", "🤖 generated with"]

BRANCH_TYPES = ("feat", "fix", "refactor", "perf", "docs", "test", "build", "ci", "chore", "deps", "style", "revert",
                "hotfix", "release", "integration")
PERMANENT_BRANCHES = {"main", "master", "develop", "trunk", "gh-pages"}
FORBIDDEN_BRANCH_WORDS = ("claude", "codex", "copilot", "cursor", "chatgpt", "gpt", "openai", "anthropic", "gemini",
                          "agent", "ai", "bot", "worktree", "tmp", "temp", "wip")


def _branch_cfg():
    b = core.CFG.get("branches") or {}
    return tuple(b.get("types") or BRANCH_TYPES), tuple(b.get("forbidden_words") or FORBIDDEN_BRANCH_WORDS)


def branch_violation(name: str):
    """Reason when a branch name breaks the GitOps naming standard, else None."""
    if not name or name in PERMANENT_BRANCHES or name.startswith(("refs/tags/", "tags/")) or name == "HEAD":
        return None
    name = name.removeprefix("refs/heads/")
    types, forbidden = _branch_cfg()
    example = "feat/PROJ-142-invoice-export, fix/login-timeout, release/26.11.4, integration/payments"
    head, _, rest = name.partition("/")
    rename = f"Rename it: {code_span(f'git branch -m {name} <type>/<topic>')}" if name else ""
    first = re.split(r"[_.-]", head.lower())[0]
    if first in forbidden:
        return (f"Branch {code_span(name)} is prefixed with a tool/agent or throwaway marker ({code_span(first)}). Branch "
                f"names describe the change, not who made it: `<type>/<ticket>-<topic>` with type in {'|'.join(types)} "
                f"(e.g. {example}). {rename}")
    if head not in types or not rest:
        return (f"Branch {code_span(name)} does not follow `<type>/<ticket>-<topic>` with type in {'|'.join(types)} "
                f"(e.g. {example}). {rename}")
    if re.search(r"(^|[-_/])[0-9a-f]{6,}$", rest) and not re.search(r"\d+\.\d+", rest):
        return (f"Branch {code_span(name)} ends in a random/generated id. Use a short descriptive kebab-case topic. "
                f"{rename}")
    if not re.match(r"^[A-Za-z0-9][A-Za-z0-9._-]*(/[a-z0-9][a-z0-9._-]*)?$", rest) or rest.lower() != rest and \
            not re.match(r"^[A-Z][A-Z0-9]+-\d+", rest):
        return (f"Branch {code_span(name)}: use lowercase kebab-case after the type (an optional ticket key like PROJ-142 "
                f"may be uppercase). {rename}")
    if len(name) > 60:
        return f"Branch {code_span(name)} is too long (max 60 characters). {rename}"
    return None


def attribution_problem(text: str) -> str | None:
    """Why `text` (a commit, tag or pull request message) may not be used, or None: it holds an AI attribution line
    (ATTRIBUTION, matched without case)."""
    low = text.lower()
    for pat in ATTRIBUTION:
        if pat in low:
            return ("User policy: no AI attribution in commits, tags or PRs. Remove the "
                    f"“{pat}” line (no Co-Authored-By/Generated-with trailers) and retry.")
    return None


def commit_problem(top: str, message: str, *, all_tracked: bool = False, adds=()) -> str | None:
    """Why devkit's own commit in the checkout `top` must not be made, or None: the message holds an AI attribution
    line (attribution_problem), or gitleaks finds secret-like content in what the commit will hold
    (security.staged_secrets: `adds` are the argument lists of `git add` commands that run first, `all_tracked` is
    `git commit -a`). A scan that could not run is said on stderr, and the commit goes on."""
    why = attribution_problem(message)
    if why:
        return why
    from .security import staged_secrets
    skipped = []
    found = staged_secrets(top, adds=[list(a) for a in adds] or None, all_tracked=all_tracked, skipped=skipped)
    if found:
        return ("gitleaks found secret-like content in the staged changes: " + "; ".join(found[:5]) +
                ". Remove the secret from the change and load it from the environment or the secret manager (rotate "
                "it if it was ever pushed). If you think it is a false positive, tell the developer: only they decide "
                "that.")
    if skipped:
        from . import ui
        ui.warn(f"the secret scan did not run: {skipped[0]}. This commit was not checked for secrets.")
    return None
