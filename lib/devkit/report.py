"""`dev report`: a structured status report (Markdown) for initiatives and projects over a period.

For each initiative: health (on track / at risk / off track), progress, milestone and due date, what was done in
the period and by whom, what is in progress, what is next, blockers and risks, and who worked on it. Then the
projects outside initiatives. Built only from the handoff repository (work items, notes, session logs), so every
machine produces the same report.
"""
from __future__ import annotations

import datetime as dt
import time

from . import registry, work

HEALTH = {"green": "🟢 On track", "amber": "🟡 At risk", "red": "🔴 Off track", "done": "✅ Done",
          "paused": "⏸ Paused"}


def health(status: str, due: str, progress, counts: dict, last_activity: float) -> tuple:
    """-> (level, reason). Plain rules, so the result can be explained."""
    today = dt.date.today()
    if status == "done":
        return "done", "finished"
    if status in ("paused", "archived"):
        return "paused", status
    if status == "blocked":
        return "red", "marked blocked"
    try:
        d = dt.date.fromisoformat(due) if due else None
    except ValueError:
        d = None
    if d and d < today:
        return "red", f"past its due date ({due})"
    if counts.get("blocked"):
        return "amber", f"{counts['blocked']} blocked task(s)"
    if d and (d - today).days <= 14 and (progress or 0) < 70:
        return "amber", f"due {due} with {progress or 0}% done"
    if last_activity and time.time() - last_activity > 14 * 86400:
        return "amber", "no activity for two weeks"
    return "green", "progressing"


def _items_in(scopes, since: str):
    done, doing, nxt, blocked = [], [], [], []
    for sc in scopes:
        for it in work.all_items(sc):
            m = it["meta"]
            who = (m.get("claimed_by") or m.get("updated_by") or "").split(" ")[0]
            row = {"id": m["id"], "title": m["title"], "who": who, "scope": sc, "priority": m.get("priority"),
                   "bucket": m.get("bucket"), "due": m.get("due")}
            st = m.get("status")
            imported = any("imported from" in e for e in it.get("changelog") or [])
            done_at_import = imported and abs(work.parse_iso(m.get("updated")) - work.parse_iso(m.get("created"))) < 900
            if st == "done" and (m.get("updated") or "") >= since and not done_at_import:
                done.append(row)
            elif st == "doing":
                doing.append(row)
            elif st == "blocked":
                blocked.append(row)
            elif st == "todo":
                nxt.append(row)
    order = {"now": 0, "next": 1, "later": 2}
    nxt.sort(key=lambda r: (order.get(r["bucket"], 3), r["priority"] != "high"))
    return done, doing, nxt, blocked


def _sessions(scopes, since_day: str) -> list:
    who = {}
    for sc in scopes:
        for ln in work.recent_sessions(sc, limit=200):
            if ln[:10] < since_day:
                continue
            parts = [p.strip() for p in ln.split("·")]
            person = next((p for p in parts if "@" in p and " " not in p), "")
            if person:
                who[person] = who.get(person, 0) + 1
    return sorted(who.items(), key=lambda x: -x[1])


def _bullets(rows, limit=6, with_who=True) -> list:
    out = [f"- {r['title']}" + (f" — {r['who']}" if with_who and r.get("who") else "") +
           (f" (due {r['due']})" if r.get("due") else "") for r in rows[:limit]]
    if len(rows) > limit:
        out.append(f"- …and {len(rows) - limit} more")
    return out


def build(days: int = 7, initiative: str = None, project: str = None) -> str:
    reg = registry.build(with_prs=False)
    since_ts = time.time() - days * 86400
    since = work.now_iso(since_ts)
    since_day = time.strftime("%Y-%m-%d", time.localtime(since_ts))
    today = time.strftime("%Y-%m-%d")
    inits = [i for i in reg.get("initiatives") or [] if not initiative or i["id"] == initiative]
    in_init = {m["id"] for i in reg.get("initiatives") or [] for m in i["members"]}
    lines = [f"# Status report · {today}", "", f"_Period: {since_day} to {today} ({days} days). Generated by "
             f"`dev report` from the handoff repository._", ""]
    summary_rows, body = [], []
    for i in inits if not project else []:
        scopes = [f"initiatives/{i['id']}"] + [m["id"] for m in i["members"]]
        done, doing, nxt, blocked = _items_in(scopes, since)
        t = i.get("tasks") or {}
        counts = {"blocked": len(blocked)}
        level, why = health(i.get("status"), i.get("due"), i.get("progress"), counts, i.get("last_activity") or 0)
        prog = f"{i['progress']}%" if i.get("progress") is not None else "—"
        summary_rows.append(f"| {i['title']} | {HEALTH[level]} | {prog} | {len(done)} | {len(doing)} | "
                            f"{len(blocked)} | {i.get('due') or '—'} |")
        body += [f"## {i['title']} — {HEALTH[level]}", "",
                 f"**Health:** {why}. **Progress:** {prog} ({t.get('done', 0)} of "
                 f"{(t.get('done', 0) or 0) + (t.get('open', 0) or 0)} tasks)"
                 + (f" · **Milestone:** {i['milestone']}" if i.get("milestone") else "")
                 + (f" · **Due:** {i['due']}" if i.get("due") else "")
                 + (f" · **Owner:** {i['owner']}" if i.get("owner") else "")
                 + f" · **Projects:** {len(i['members'])}", ""]
        if i.get("goal"):
            body += [f"**Goal:** {i['goal'].strip().splitlines()[0]}", ""]
        body += ["**Done this period**"] + (_bullets(done) or ["- Nothing completed."]) + [""]
        body += ["**In progress**"] + (_bullets(doing) or ["- Nothing in progress."]) + [""]
        body += ["**Next**"] + (_bullets(nxt, 4, with_who=False) or ["- No open tasks."]) + [""]
        risks = [r.strip("-• ").strip() for r in (i.get("risks") or "").splitlines() if r.strip().startswith(("-", "•"))]
        if blocked or risks:
            body += ["**Blockers and risks**"] + _bullets(blocked) + [f"- {r}" for r in risks[:3]] + [""]
        people = _sessions(scopes, since_day)
        if people:
            body += ["**Team:** " + ", ".join(f"{p} ({n} session{'s' if n != 1 else ''})" for p, n in people[:6]), ""]
    if not initiative:
        rows = []
        for p in reg["projects"]:
            if p["id"] in in_init or (project and p["id"] != project):
                continue
            ns = p.get("note_summary") or {}
            if ns.get("status") == "archived":
                continue
            done, doing, nxt, blocked = _items_in([p["id"]], since)
            level, why = health(ns.get("status", "active"), ns.get("due"), p.get("progress"), {"blocked": len(blocked)},
                                p.get("last_activity") or 0)
            prog = f"{p['progress']}%" if p.get("progress") is not None else "—"
            rows.append(f"| {p['id']} | {HEALTH[level]} | {prog} | {len(done)} | {len(doing)} | "
                        f"{'; '.join(r['title'] for r in (doing or nxt)[:1]) or '—'} |")
            if project:
                body += [f"## {p['id']} — {HEALTH[level]}", "", f"**Health:** {why}. **Progress:** {prog}", "",
                         "**Done this period**"] + (_bullets(done) or ["- Nothing completed."]) + [""] + \
                        ["**In progress**"] + (_bullets(doing) or ["- Nothing in progress."]) + [""] + \
                        ["**Next**"] + (_bullets(nxt, 4, False) or ["- No open tasks."]) + [""]
        if rows and not project:
            body += ["## Projects outside initiatives", "",
                     "| Project | Health | Progress | Done | In progress | Now / next |", "|---|---|---|---|---|---|",
                     *rows, ""]
    if summary_rows:
        lines += ["## Summary", "", "| Initiative | Health | Progress | Done | In progress | Blocked | Due |",
                  "|---|---|---|---|---|---|---|", *summary_rows, ""]
    return "\n".join(lines + body).rstrip() + "\n"
